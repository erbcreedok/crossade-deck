//
// Череду считает игра, и считает её КАЖДЫЙ экран — она читается по столу, который у всех один.
// Если бы о ней докладывали все, комната получала бы столько одинаковых сообщений, сколько людей за
// столом, на каждый ход.
//
// Поэтому говорит один: тот, кто сидит на первом из занятых мест. Правило ни с кем не
// согласовывается — каждый экран считает его сам по тому же ростеру и приходит к тому же ответу, а
// когда говоривший уходит, следующий начинает говорить без единого сообщения между ними.

/** Мой ли черёд докладывать о ходе. */
export function speaksForTable(present: readonly { seat: string }[], mySeat: string | null): boolean {
  if (!mySeat || present.length === 0) return false;
  const first = present.map((one) => one.seat).sort()[0];
  return first === mySeat;
}
