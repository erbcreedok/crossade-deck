import type { AcceptRule } from "./boardZone";

// ПРАВИЛА ПРИЁМА КАК ДАННЫЕ — готовые `AcceptRule` для доски.
//
// `BoardZone.rule` — элемент-слой цепочки приёма: последний гейт поверх `onOccupied`, и нарушить
// его нельзя ничем. Сама зона про значения ничего не знает и знать не должна: ранг, масть, цвет
// клетки — это правила ИГРЫ, а не устройство доски. Поэтому они живут отдельными функциями и
// подставляются снаружи.
//
// Файл чистый (Pixi не импортируется) — значит проверяется юнитом, а не глазами.

/**
 * «Только на клетку своего цвета» — шахматный слонов ход в самой простой форме.
 *
 * Обе карты (цвет фигуры и цвет клетки) приходят СНАРУЖИ и ровно те же, что рисует разметка: если
 * бы правило считало цвет само, картинка и правило разошлись бы при первой же смене раскладки, и
 * витрина показывала бы одно, а зона делала другое.
 *
 * Неизвестная фигура или неизвестный слот — отказ: правило приёма ошибается в сторону «нельзя»,
 * иначе дыра в данных читается как разрешение.
 */
export function sameColorRule(figureDark: ReadonlyMap<string, boolean>, slotDark: ReadonlyMap<string, boolean>): AcceptRule {
  return ({ figureId, toKey }) => {
    const f = figureDark.get(figureId);
    const s = slotDark.get(toKey);
    return f !== undefined && s !== undefined && f === s;
  };
}
