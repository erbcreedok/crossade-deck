import { burnFrame } from "../effects/burn";
import { TEX_H, TEX_W } from "../engine/constants";
import { easeOutQuad } from "./easing";

// СТИЛИ УНИЧТОЖЕНИЯ карты — реестр, сестра flipStyles.ts.
//
// «Сжечь» был единственным способом убрать карту со стола, и жил он отдельным эффектом с
// собственным вызовом (`Card.burn()`). Это неверно уже по названию: горение — ОДИН из способов
// уничтожения, а не синоним. Шреддер, растворение, улёт за край — такие же способы, и заводить
// под каждый свой метод значит переписывать карту на каждую хотелку дизайнера.
//
// Стиль отвечает на один вопрос: как выглядит карта в момент `t` от начала уничтожения. Движок
// только применяет ответ; когда карта считается мёртвой, решает он же — по длительности.
//
// КАК ЗАДАТЬ СВОЙ. Передать объектом в пресет — регистрировать не нужно. Реестр ниже это список
// готовых и точка для сериализуемых конфигов. Она сразу появится в пресетах, в панели
// каталога и в игре — движок, карта и стори не правятся. Функция обязана быть ЧИСТОЙ: тогда её
// проверяет юнит, а Pixi в node не исполняется и другого способа проверить нет.

/**
 * Как выглядит карта в этот момент эффекта. Отклонения от дома, а не абсолютные координаты.
 *
 * Один тип на появление и на уничтожение намеренно: это одно и то же движение, пройденное в разные
 * стороны, и разводить их по двум одинаковым интерфейсам значило бы дважды описывать одно.
 */
export interface EffectFrame {
  /** Сдвиг от дома, в пикселях контента. */
  dx: number;
  dy: number;
  /** Добавочный поворот, рад. */
  rot: number;
  /** Множитель размера. */
  scale: number;
  /** Прозрачность 0..1. */
  alpha: number;
  /**
   * Видимая часть карты — список полигонов в ЛОКАЛЬНЫХ координатах текстуры (центр 0,0).
   * null — маски нет, карта видна целиком. Несколько полигонов нужны шреддеру: у него видимых
   * кусков много, и одним контуром их не описать.
   */
  mask: number[][] | null;
  /** Множитель высоты тени; null — тень убрать. */
  shadow: number | null;
}

/** Прежнее имя кадра — уничтожение пользуется тем же типом, что и появление. */
export type DestroyFrame = EffectFrame;

export interface EffectCtx {
  /** Непрерывный возраст карты — для дрожи и волн, которые не должны зависеть от начала эффекта. */
  age: number;
  /** Ширина карты в координатах контента (не текстуры). */
  width: number;
}

export type DestroyCtx = EffectCtx;

/**
 * Чем задаётся стиль: САМИМ стилем или именем из реестра.
 *
 * Объект первичен. Строка — сокращение для готовых и для конфигов, которые сериализуются
 * (docs/PORTABILITY.md: конфиг доски обязан быть данными). Требовать регистрации ради того, чтобы
 * подставить свою функцию, было бы прямым запретом на «свою анимацию».
 */
export type DestroyStyleRef = DestroyStyle | string;

export interface DestroyStyle {
  label: string;
  /** Своя длительность, сек. Пресет её масштабирует общим `speed`. */
  dur: number;
  frame: (t: number, ctx: EffectCtx) => EffectFrame;
}

export const NEUTRAL_FRAME: EffectFrame = { dx: 0, dy: 0, rot: 0, scale: 1, alpha: 1, mask: null, shadow: 1 };
const clamp01 = (v: number) => Math.max(0, Math.min(1, v));

/** Прямоугольник текстуры как полигон — основа всех масок-окон. */
export function rect(x: number, y: number, w: number, h: number): number[] {
  return [x, y, x + w, y, x + w, y + h, x, y + h];
}

export const DESTROY_STYLES: Readonly<Record<string, DestroyStyle>> = {
  burn: {
    label: "сжечь — замирание с дрожью, потом расход волнистым фронтом снизу вверх",
    dur: 0.64,
    // Делегирует существующему `effects/burn.ts`: у горения своя геометрия фронта, свои тесты и
    // своя история багов (недогоревшая полоска у верхней кромки). Переписывать её здесь ради
    // единообразия значило бы завести второй фронт горения и вторую такую же историю.
    frame: (t, ctx) => {
      const f = burnFrame(t, ctx.age, ctx.width);
      return {
        dx: f.jitterX,
        dy: f.jitterY,
        rot: 0,
        scale: 1,
        alpha: 1, // видимость съедает МАСКА, а не затухание — иначе карта гасла бы дважды
        mask: f.dissolve ? [f.dissolve.maskPoints] : null,
        shadow: f.dissolve ? f.dissolve.shadowShrink : 1,
      };
    },
  },

  shred: {
    label: "шреддер — карта режется на полосы, и каждая уезжает вниз своим темпом",
    dur: 0.75,
    frame: (t, ctx) => {
      const p = clamp01(t / 0.75);
      const strips = 9;
      const sw = TEX_W / strips;
      const mask: number[][] = [];
      for (let i = 0; i < strips; i++) {
        // Полосы уезжают вразнобой: соседние с разной задержкой, иначе это не резка, а сползание
        // целого листа. Чередование через одну даёт узнаваемый «зубчатый» край.
        const lag = (i % 2 === 0 ? i : strips - i) / strips;
        const q = clamp01((p - lag * 0.35) / 0.65);
        if (q >= 1) continue; // полоса уехала целиком
        const top = -TEX_H / 2 + TEX_H * q; // видимое окно съезжает вниз и укорачивается
        mask.push(rect(-TEX_W / 2 + i * sw, top, sw, TEX_H - TEX_H * q));
      }
      return { ...NEUTRAL_FRAME, dy: p * ctx.width * 0.1, mask, shadow: p > 0.8 ? null : 1 - p };
    },
  },

  fade: {
    label: "растворение — карта просто гаснет, чуть проседая",
    dur: 0.45,
    frame: (t) => {
      const p = clamp01(t / 0.45);
      return { ...NEUTRAL_FRAME, alpha: 1 - easeOutQuad(p), scale: 1 - p * 0.08, shadow: p > 0.7 ? null : 1 - p };
    },
  },

  flyRight: {
    label: "улёт вправо — карта уходит за край, закручиваясь",
    dur: 0.55,
    frame: (t, ctx) => {
      const p = clamp01(t / 0.55);
      const e = easeOutQuad(p);
      return {
        ...NEUTRAL_FRAME,
        dx: e * ctx.width * 7, // заведомо за кромку витрины, какой бы она ни была
        dy: -e * ctx.width * 0.4,
        rot: e * 1.1,
        // Гаснет ПОЗДНО: карта должна улететь, а не растаять на месте. Затухание тут — чтобы не
        // мигнуть на кромке канваса, а не самостоятельный эффект.
        alpha: 1 - clamp01((p - 0.6) / 0.4),
        shadow: p > 0.5 ? null : 1 - p * 2,
      };
    },
  },

  shrink: {
    label: "схлопывание — карта уменьшается в точку, проворачиваясь",
    dur: 0.4,
    frame: (t) => {
      const p = clamp01(t / 0.4);
      return { ...NEUTRAL_FRAME, scale: 1 - easeOutQuad(p), rot: p * 1.6, alpha: 1 - p * 0.3, shadow: p > 0.6 ? null : 1 - p };
    },
  },
};

export const DESTROY_STYLE_IDS: string[] = Object.keys(DESTROY_STYLES);

/** Стиль по имени. Неизвестное — горение: оно было единственным и остаётся дефолтом стола. */
export function destroyStyle(v: DestroyStyleRef): DestroyStyle {
  // Объект — берём как есть. Реестр НУЖЕН только каталогу и конфигам, которые ссылаются именем;
  // регистрировать свой стиль, чтобы им воспользоваться, не требуется.
  if (typeof v !== "string") return v;
  return DESTROY_STYLES[v] ?? DESTROY_STYLES.burn!;
}
