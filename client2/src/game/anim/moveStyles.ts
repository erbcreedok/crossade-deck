import { easeOutQuad } from "./easing";

// СТИЛИ ПЕРЕМЕЩЕНИЯ — как элемент летит, когда его двигает ПРОГРАММА (команда доски, сервер,
// правило игры), а не палец.
//
// Драг — не отсюда: там траекторию задаёт рука, и движку остаётся только успевать. А вот
// «карта пошла в сброс», «конь встал на клетку пешки», «фишка прилетела в банк» — это движение,
// которое кто-то СПРОЕКТИРОВАЛ, и выглядеть оно может очень по-разному.
//
// До сих пор способ был ровно один: поставить пружине новую цель и ждать. Пружина хороша тем, что
// её не надо считать, и плоха тем, что она всегда одинаковая — по прямой, с одинаковым характером.
// Дугой над столом, прыжком, рывком с оттяжкой ею не полетишь.
//
// КАК ЗАДАТЬ СВОЙ. Передать объектом в пресет; реестр — список готовых. Функция получает прогресс и возвращает, ГДЕ элемент
// относительно прямой от старта к цели: `along` — доля пути (0 — старт, 1 — цель), `lift` — увод
// в сторону, перпендикулярно пути, в долях его длины. Требования те же: чистая, и на концах
// строго 0 и 1, иначе элемент не долетит до собственной цели.

export interface MoveFrame {
  /** Доля пройденного пути по прямой старт→цель. 0 — старт, 1 — цель. */
  along: number;
  /**
   * ВЫСОТА над столом в этот момент полёта, в долях длины пути.
   *
   * Именно высота, а не сдвиг позиции. Пока это был перпендикулярный сдвиг, тень летела по той же
   * дуге и оставалась ровно под картой: перспектива пропадала, и «дуга» ничем не отличалась от
   * прямой. Высота же поднимает картинку и одновременно отпускает тень — зазор между ними и есть
   * то, что читается как полёт над столом.
   */
  lift: number;
  /** Добавочный поворот, рад. */
  rot: number;
  /** Множитель размера — «выше над столом» читается как «крупнее». */
  scale: number;
}

/**
 * Чем задаётся стиль: САМИМ стилем или именем из реестра.
 *
 * Объект первичен. Строка — сокращение для готовых и для конфигов, которые сериализуются
 * (docs/PORTABILITY.md: конфиг доски обязан быть данными). Требовать регистрации ради того, чтобы
 * подставить свою функцию, было бы прямым запретом на «свою анимацию».
 */
export type MoveStyleRef = MoveStyle | string;

export interface MoveStyle {
  label: string;
  /** Базовая длительность, сек. `spring` её не использует — там время задаёт физика. */
  dur: number;
  /** null — движение отдаётся ПРУЖИНЕ (физика вместо расписания). */
  frame: ((p: number) => MoveFrame) | null;
}

const flat = (along: number): MoveFrame => ({ along, lift: 0, rot: 0, scale: 1 });
const hump = (p: number) => Math.sin(Math.PI * Math.max(0, Math.min(1, p)));

export const MOVE_STYLES: Readonly<Record<string, MoveStyle>> = {
  spring: {
    label: "пружина — как при драге: летит по прямой, слегка перелетая цель. Дефолт стола",
    dur: 0,
    // null НЕ означает «ничего не делать»: движение отдаётся пружинам тела (anim/config.ts).
    // Именно так стол вёл себя всегда, и это остаётся значением по умолчанию, а не пережитком.
    frame: null,
  },

  arc: {
    label: "дуга — элемент поднимается над столом и опускается на цель",
    dur: 0.5,
    frame: (p) => ({ along: easeOutQuad(p), lift: hump(p) * 0.28, rot: 0, scale: 1 + hump(p) * 0.15 }),
  },

  hop: {
    label: "прыжок — два коротких скачка, как переставляют фигуру рукой",
    dur: 0.55,
    frame: (p) => {
      // Два горба: первый выше. Путь идёт равномерно, «прыгает» только высота — иначе элемент
      // зависал бы в воздухе между скачками.
      const h = p < 0.55 ? hump(p / 0.55) : hump((p - 0.55) / 0.45) * 0.45;
      return { along: p, lift: h * 0.3, rot: 0, scale: 1 + h * 0.12 };
    },
  },

  slide: {
    label: "скольжение — по прямой, без подъёма и без перелёта",
    dur: 0.35,
    frame: (p) => flat(easeOutQuad(p)),
  },

  swoop: {
    label: "заход — элемент проскакивает мимо цели и возвращается на неё",
    dur: 0.6,
    frame: (p) => {
      const e = easeOutQuad(p);
      // Перелёт до 1.12 и возврат: «оттяжка» в конце читается как вес.
      const over = e + Math.sin(Math.PI * p) * 0.12 * (1 - p);
      return { along: over, lift: hump(p) * 0.12, rot: Math.sin(Math.PI * p) * 0.25, scale: 1 };
    },
  },
};

export const MOVE_STYLE_IDS: string[] = Object.keys(MOVE_STYLES);

/** Стиль по имени. Неизвестное — пружина: так стол двигал элементы всегда. */
export function moveStyle(v: MoveStyleRef): MoveStyle {
  // Объект — берём как есть. Реестр НУЖЕН только каталогу и конфигам, которые ссылаются именем;
  // регистрировать свой стиль, чтобы им воспользоваться, не требуется.
  if (typeof v !== "string") return v;
  return MOVE_STYLES[v] ?? MOVE_STYLES.spring!;
}

/**
 * Точка на пути по кадру стиля. Вынесено отдельно, потому что это единственное место, где
 * «доля пути + увод вбок» превращается в координаты, и повторять эту тригонометрию у каждого
 * вызывающего значило бы получить пять слегка разных дуг.
 */
export function pointOnPath(from: { x: number; y: number }, to: { x: number; y: number }, f: MoveFrame): { x: number; y: number } {
  const dx = to.x - from.x;
  const dy = to.y - from.y;
  // МЕСТО НА СТОЛЕ — строго по прямой. Подъём сюда не входит: он высота (`lift`), и её применяет
  // элемент, поднимая картинку и отпуская тень.
  return { x: from.x + dx * f.along, y: from.y + dy * f.along };
}

/** Высота полёта в пикселях: доля от длины пути. */
export function liftPixels(from: { x: number; y: number }, to: { x: number; y: number }, f: MoveFrame): number {
  return Math.hypot(to.x - from.x, to.y - from.y) * f.lift;
}
