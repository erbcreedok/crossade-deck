// ПРЕСЕТЫ КРУГА СТОЛА — настройки-как-данные под одним именем: как круг ведёт себя, когда карт
// становится больше. Пресет переиспользуется любой спекой (песочница, витрина, крестовый) и позже
// станет рычагом контекстного меню — поэтому это ДАННЫЕ, а не ветка в билдере.
//
// Два поведения, оба нужны:
//   • grow — круг растёт с числом карт без предела (прежний закон всех бордов). Столу, где карт
//     заранее немного, так честнее: карты никогда не наезжают друг на друга;
//   • capped — круг размечен «как под min карт» сразу и не растёт выше «как под max»: дальше карты
//     ужимаются по нему плотнее, веером. Так стол не раздувается от каждой новой карты и не
//     утаскивает за собой внешний круг (он считается от центра), а значит и масштаб не проседает.

export interface RingPreset {
  /** Минимум позиций круга: пустой стол сразу размечен под столько карт — не «точка», в которую
   *  неудобно целиться. Число мест всё равно перебивает минимум, если игроков больше. */
  readonly min: number;
  /** Потолок круга в позициях (0 — без потолка): дальше радиус стоит, карты уходят в нахлёст. */
  readonly max: number;
}

export const RING_PRESETS = {
  grow: { min: 0, max: 0 },
  /** Кадр владельца 2026-08-05: старт «как под 4 карты», потолок «как под 7» — при ячейке 150×215
   *  это круг стороной 770, вокруг которого ещё остаётся кольцо в три карты. */
  capped: { min: 4, max: 7 },
} as const satisfies Record<string, RingPreset>;

export type RingPresetName = keyof typeof RING_PRESETS;

/** Пресет по имени или свой набор чисел — рычаг принимает и то, и то. */
export function ringPresetOf(ring: RingPresetName | RingPreset | undefined): RingPreset {
  if (!ring) return RING_PRESETS.grow;
  return typeof ring === "string" ? RING_PRESETS[ring] : ring;
}
