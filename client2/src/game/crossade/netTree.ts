// ДЕРЕВО СЕТЕВОГО СТОЛА — контракт, общий для всех столов на снимке (Crossade, дебаг-стол
// Multiplayer, live). Дерево — ВИД состояния, а не второй источник правды: любое изменение снимка
// пересобирает его целиком (дёшево — карт немного, слотов ещё меньше).
//
// Контракт живёт отдельным файлом, чтобы общая сцена (tableScene.ts) зависела от формы дерева, а не
// от конкретной геометрии: столы расходятся составом слотов (у дебаг-стола нет ни колоды, ни
// сброса), но спрашивают у дерева одно и то же.

import type { Group, Size, Vec } from "../slot/types";

export interface NetTree {
  readonly root: Group;
  /** Габарит содержимого: не меньше доски, больше — если рука/play-зона переросли базовый габарит. */
  readonly size: Size;
  readonly origins: Readonly<Record<string, Vec>>;
  /** Центр карты в координатах доски (позиция покоя). null — карты на доске нет. */
  homeOf(cardId: string): Vec | null;
  /** Слот, в котором лежит карта. */
  slotOf(cardId: string): string | null;
  /** Слот-дропзона под точкой доски (по тому же дереву, что и рендер). */
  slotAt(cp: Vec): string | null;
}
