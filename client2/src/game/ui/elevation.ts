// ВЫСОТА НАД СТОЛОМ — третья ось, `z`.
//
// Стол рисуется в 2D, и «вверх» тут значит две РАЗНЫЕ вещи. Пока у второй не было имени, они
// смешивались в одних формулах, и тень трижды вела себя наоборот: то росла при спуске, то уезжала
// вверх, когда карта опускалась.
//
//   ЭКРАН (x, y) — плоскость картинки. Ось Y растёт ВНИЗ. Это место предмета НА СТОЛЕ.
//   ВЫСОТА (z)   — над столом. 0 — лежит; больше — выше. Ось направлена К ЗРИТЕЛЮ, не «вверх по
//                  экрану». Это НЕ координата: у предмета есть своё место на столе, и подъём его
//                  не меняет.
//
// ПРАВИЛО, из-за нарушения которого всё и ломалось: `z` — ИСТОЧНИК, экранное смещение и тень —
// СЛЕДСТВИЯ. Ничто не двигает карту по экрану напрямую «чтобы выглядело выше»: сначала меняется
// `z`, а подъём картинки и поведение тени выводятся из него. Иначе одно и то же событие
// (карта поднялась) описывается в двух местах, и рано или поздно они начинают спорить.
//
// ЧТО ДАЁТ ВЫСОТУ: только то, что МЕНЯЕТ РАЗМЕР предмета. Ближе к зрителю — крупнее; это и есть
// единственный признак, по которому высоту вообще видно на плоской картинке.
//   • поза покоя — lifted и held подняты над столом (масштаб больше единицы);
//   • эффекты — взлёт при появлении, подброс при перевороте: они масштабируют предмет.
//
// ЧЕГО ВЫСОТА НЕ ДАЁТ: idle-дыхание. Карта при нём не меняется в размере и не меняет слой, значит
// и высота её не меняется — это ЭКРАННОЕ покачивание, декорация. Пока дыхание кормило `z`, тень
// дышала вместе с ним: меняла размер и ползала под неподвижной по сути картой.
//
// ЧТО ИЗ НЕЁ СЛЕДУЕТ:
//   • картинка ползёт вверх по экрану (ось Y вниз → вычитаем);
//   • тень уходит дальше вниз-влево и растёт;
//   • слой отрисовки: чем выше, тем позже рисуется (levelOf).

/** Насколько поднятый предмет уезжает вверх ПО ЭКРАНУ, в долях своей высоты на единицу `z`. */
export const SCREEN_LIFT_PER_Z = 0.55;

/**
 * Экранное смещение от высоты. Отрицательное — вверх по экрану: ось Y растёт вниз, и это ровно то
 * место, где раньше терялся знак.
 */
export function screenLift(z: number, cardH: number): number {
  return -z * cardH * SCREEN_LIFT_PER_Z;
}

/**
 * Высота от позы покоя. Масштаб — способ ПОКАЗАТЬ высоту (ближе к зрителю = крупнее), поэтому
 * превышение масштаба над лежащим состоянием и есть `z`.
 */
export function zFromScale(scale: number): number {
  return Math.max(0, scale - 1);
}

/**
 * ЭКРАННОЕ покачивание дыхания, px. Не высота: размер предмета при нём не меняется, а значит
 * расстояние до зрителя тоже. Тень на это не реагирует — и правильно делает.
 */
export function bobOffset(sinPhase: number, amp: number, cardH: number): number {
  return sinPhase * cardH * amp;
}

/**
 * Дышит ли предмет в этой позе.
 *
 * Дыхание — АНИМАЦИЯ, доступная чему угодно на столе, а не свойство поднятого состояния: лежащая
 * карта имеет полное право покачиваться, если сцена этого просит. Поза задаёт лишь УМОЛЧАНИЕ —
 * поднятый предмет дышит сам собой, потому что висит в воздухе, — а явное значение его перебивает.
 *
 * Ось отдельная ещё и потому, что гасят их порознь: `reduce-motion` останавливает дыхание, не
 * трогая позу, и поднятая карта остаётся поднятой.
 */
export function idleBobs(state: string, override?: boolean): boolean {
  return override ?? state === "lifted";
}

/**
 * Насколько предмет крупнее на единицу высоты. Единица — не подгонка: `zFromScale` считает высоту
 * как превышение масштаба над лежащим, и обратный перевод обязан быть тем же, иначе «поднять на
 * 0.2» и «увеличить на 0.2» дадут разную высоту.
 */
export const SCALE_PER_Z = 1;

/** Масштаб от высоты. Лежащий (z = 0) — единица: на столе никто не крупнее себя. */
export function scaleFromZ(z: number): number {
  return 1 + z * SCALE_PER_Z;
}
