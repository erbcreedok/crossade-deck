// ЧИСТАЯ математика витрины стори: габарит содержимого и вписывание его в экран. Вынесена из
// KitScene отдельно ровно потому, что всё остальное там — Pixi, а Pixi в node не исполняется
// (docs/HANDOFF.md: «зелёные гейты про канвас не значат ничего»). Что можно проверить юнитом —
// проверяется юнитом.

export interface Extent {
  w: number;
  h: number;
}

export interface Footprint {
  x: number;
  y: number;
  hw: number;
  hh: number;
}

/**
 * Габарит витрины: правый-нижний край содержимого плюс поле.
 *
 * УСЛОВНОСТЬ КООРДИНАТ (та же, что в песочнице): содержимое живёт в ПОЛОЖИТЕЛЬНОЙ четверти,
 * (0,0) — левый верхний угол витрины. Камера сцены раскладывает контент в прямоугольнике
 * [0..w]×[0..h] и всё, что левее или выше нуля, обрезает — поэтому мерить bounding box с
 * отрицательными краями было бы бессмысленно: габарит получился бы верный, а половина витрины
 * оставалась бы за кромкой. Элемент прибит за ЦЕНТР, поэтому первый ставится в (padding+hw, padding+hh).
 *
 * Меряем полуразмерами (hw/hh), а не позициями: витрина из одной карты иначе получила бы нулевую ширину.
 */
export function extentOf(items: readonly Footprint[], padding: number): Extent {
  // Пустая витрина всё равно должна иметь размер: камера делит экран на габарит контента,
  // а деление на ноль даёт NaN и «чёрный канвас без объяснений».
  let maxX = 0;
  let maxY = 0;
  for (const it of items) {
    if (it.x + it.hw > maxX) maxX = it.x + it.hw;
    if (it.y + it.hh > maxY) maxY = it.y + it.hh;
  }
  return { w: Math.max(1, maxX + padding), h: Math.max(1, maxY + padding) };
}

// Пределы зума витрины шире, чем у стола: компонент рассматривают вплотную (пиксели рубашки,
// кромка карты), и упереться в потолок камеры игры тут было бы обидно.
export const MIN_KIT_ZOOM = 0.4;
export const MAX_KIT_ZOOM = 4;

/**
 * Нижний предел АВТОВПИСЫВАНИЯ — отдельный от предела ручной камеры, и это не придирка.
 *
 * `MIN_KIT_ZOOM` отвечает на вопрос «насколько мелко человеку разрешено уводить камеру руками».
 * Подставлять его во вписывание нельзя: широкая секция на телефоне требует зума меньше 0.4, а
 * пол его не даёт — и вписывание молча возвращало зум, при котором содержимое НЕ ПОМЕЩАЕТСЯ.
 * Канвас обрезал витрину по обоим краям, причём без всякого признака, что что-то потеряно.
 *
 * Каталог обязан показать компонент ЦЕЛИКОМ. Если ради этого нужен зум 0.15 — значит 0.15;
 * «мелко, но видно» честнее, чем «крупно и наполовину за кадром». Пол оставлен только как защита
 * от вырожденных величин.
 */
export const MIN_FIT_ZOOM = 0.08;

/**
 * Верхний предел АВТОВПИСЫВАНИЯ — 1:1, и по той же причине, по которой отдельный нижний.
 *
 * `MAX_KIT_ZOOM` — потолок для РУЧНОГО разглядывания (пиксели рубашки, кромка карты). Подставлять
 * его во вписывание нельзя: канвас во весь фрейм — это много места, и вписывание раздуло бы одну
 * кнопку вчетверо просто потому, что место есть. Каталог показывает вещь такой, какой она приходит
 * на стол: уменьшить, если не влезает, — можно; увеличить сверх настоящего размера — нет.
 */
export const MAX_FIT_ZOOM = 1;

/**
 * Какой ВЫСОТЫ должен быть канвас, чтобы под витриной не оставалось пустого сукна.
 *
 * Высоту хосту задаёт вёрстка страницы, а не сцена, и раньше это была просто «вся высота окна»:
 * стори с одной кнопкой печаталась во весь экран, и 90% канваса было зелёным ничем.
 *
 * Считать её надо ТЕМ ЖЕ зумом, который потом выберет `fitZoom`, иначе высота и картинка
 * разъедутся. Круга тут нет: `fitZoom` берёт меньший из двух коэффициентов, ширину задаёт
 * страница — значит коэффициент по ширине известен заранее, и высота по нему получается такой,
 * что вертикальный коэффициент выходит ровно тем же.
 *
 * УВЕЛИЧИВАТЬ ВЫШЕ 1:1 НЕЛЬЗЯ. `MAX_KIT_ZOOM` — потолок для РУЧНОГО разглядывания (пиксели
 * рубашки, кромка карты), и подставлять его сюда значит раздувать компонент только потому, что
 * страница широкая: одна кнопка растягивалась на пол-экрана и переставала быть похожей на себя.
 * Каталог показывает вещь такой, какой она приходит на стол. Уменьшать — можно, для этого и
 * нижний предел.
 */
/** Что витрине нужно знать о расставленном элементе, чтобы посчитать габарит. */
export interface PlacedItem {
  home: { x: number; y: number };
  footprint: { hw: number; hh: number };
  /** Масштаб ПОЗЫ: удерживаемая карта нарисована крупнее лежащей. */
  restScale: number;
}

/**
 * Габарит витрины по расставленным элементам.
 *
 * Полуразмеры берутся В ПОЗЕ, а не в покое, и это не мелочь: удерживаемая карта рисуется крупнее
 * (DRAG_SCALE), и по номинальному размеру она вылезала за габарит — на канвасе, поджатом ровно по
 * нему, ей срезало верх. Именно это было видно в разделе «Тень» на телефоне.
 */
export function extentOfPlaced(items: readonly PlacedItem[], padding: number): Extent {
  return extentOf(
    items.map((p) => ({ x: p.home.x, y: p.home.y, hw: p.footprint.hw * p.restScale, hh: p.footprint.hh * p.restScale })),
    padding,
  );
}

/**
 * КОРОБКА КАНВАСА под витрину: сколько места ей нужно на самом деле, не больше.
 *
 * Канвас не «занимает фрейм», а занимает витрину. Растянутый во весь фрейм он врёт дважды: под
 * одной картой лежит пол-экрана зелёного сукна, будто раздел про поле, а не про карту; а на узком
 * окне широкая витрина ВЫЛЕЗАЕТ за кромку и достать её нечем — прокрутки у канваса нет, и часть
 * раздела просто перестаёт существовать для смотрящего.
 *
 * Отсюда оба предела разом: не больше фрейма (иначе край срезан) и не крупнее 1:1 (иначе одна
 * кнопка раздувается на пол-экрана просто потому, что место есть). Между ними — размер витрины.
 */
export function fitCanvas(extent: Extent, frame: Extent): Extent {
  if (!(extent.w > 0) || !(extent.h > 0)) return { w: Math.max(1, frame.w), h: Math.max(1, frame.h) };
  const k = fitScale(extent, frame);
  return { w: Math.ceil(extent.w * k), h: Math.ceil(extent.h * k) };
}

/** Во сколько раз ужать витрину, чтобы влезла во фрейм. Больше 1:1 не увеличиваем НИКОГДА. */
export function fitScale(extent: Extent, frame: Extent): number {
  const byW = frame.w > 0 ? frame.w / extent.w : 1;
  const byH = frame.h > 0 ? frame.h / extent.h : 1;
  return Math.max(MIN_FIT_ZOOM, Math.min(MAX_FIT_ZOOM, byW, byH));
}

export function fitHeight(extent: Extent, hostW: number): number | null {
  if (!(extent.w > 0) || !(extent.h > 0) || !(hostW > 0)) return null;
  const k = Math.max(MIN_FIT_ZOOM, Math.min(1, hostW / extent.w));
  return Math.ceil(extent.h * k);
}

/** Зум, при котором витрина видна ЦЕЛИКОМ. Меньший из двух коэффициентов, зажатый в [min, max]. */
/**
 * Камера витрины. Отличий от игровой ровно два, и оба выстраданные.
 *
 * По ЦЕНТРУ, а не по левой опоре: витрина — один компонент, ему уместно стоять посередине (у
 * песочницы align:"left", потому что там вертикальная лента секций). `margin: 0` — тоже не косметика:
 * верхний отступ камеры осмыслен там, где контент выше экрана и его прижимают к верху, а у витрины
 * поле СВОЁ (`padding`) и уже сидит внутри габарита — вторая рамка поверх него только сдвигала
 * содержимое вниз, ровно на столько же срезая снизу, и кнопка стояла не по центру.
 *
 * Пределы зума СВОИ: игровая камера не опускается ниже 0.6, и для стола это верно — незачем
 * разглядывать поле с высоты птичьего полёта. Витрине же приходится вписывать широкую секцию в узкий
 * экран телефона, и пол 0.6 не давал этого сделать: `fitZoom` честно считал 0.39, а `setZoom` молча
 * поднимал его обратно до 0.6, и витрина обрезалась по обоим краям без всякого признака потери.
 */
export const KIT_CAMERA = { align: "center", alignY: "center", margin: 0, minZoom: MIN_FIT_ZOOM, maxZoom: MAX_KIT_ZOOM } as const;

export function fitZoom(extent: Extent, screen: Extent, minZoom: number, maxZoom: number): number {
  // Первый кадр приходит с нулевым экраном (хост ещё не померен) — тогда просто отдаём minZoom,
  // иначе Infinity/NaN уедет в матрицу камеры и сцена не покажется вообще.
  if (!(extent.w > 0) || !(extent.h > 0) || !(screen.w > 0) || !(screen.h > 0)) return minZoom;
  const z = Math.min(screen.w / extent.w, screen.h / extent.h);
  return Math.max(minZoom, Math.min(maxZoom, z));
}
