import { describe, it, expect } from "vitest";
import { extentOf, fitZoom } from "./kitExtent";

// Габарит витрины и вписывание её в экран. Это ЕДИНСТВЕННАЯ математика в хосте стори, поэтому
// только она тут и покрыта: остальное в KitScene — работа с Pixi, которую node не исполняет.

describe("extentOf", () => {
  it("пустая витрина не даёт нулевой габарит — камера с 0×0 делит на ноль", () => {
    const e = extentOf([], 24);
    expect(e.w).toBeGreaterThan(0);
    expect(e.h).toBeGreaterThan(0);
  });

  it("меряет по КРАЯМ элементов, а не по их центрам", () => {
    // Элемент прибит за центр: поставленный в (padding+hw), он касается левого поля ровно,
    // а правый край даёт габарит. 10 + 2×50 = 110, плюс поле справа = 120.
    const e = extentOf([{ x: 60, y: 80, hw: 50, hh: 70 }], 10);
    expect(e).toEqual({ w: 120, h: 160 });
  });

  it("габарит по САМОМУ дальнему элементу", () => {
    const e = extentOf(
      [
        { x: 20, y: 10, hw: 10, hh: 10 },
        { x: 100, y: 10, hw: 10, hh: 10 },
      ],
      5,
    );
    expect(e.w).toBe(115);
  });

  it("содержимое левее/выше нуля габарит НЕ расширяет — оно просто вне витрины", () => {
    // Условность: (0,0) — левый верхний угол, камера обрезает всё до него. Молча раздвинуть
    // габарит влево нельзя: контент всё равно окажется за кромкой, просто витрина станет шире
    // и «съедет» — а причина останется невидимой.
    const e = extentOf([{ x: -100, y: -100, hw: 10, hh: 10 }], 8);
    expect(e).toEqual({ w: 8, h: 8 });
  });

  it("элемент нулевого размера не ломает счёт", () => {
    const e = extentOf([{ x: 5, y: 5, hw: 0, hh: 0 }], 4);
    expect(e).toEqual({ w: 9, h: 9 });
  });
});

describe("fitZoom", () => {
  it("витрина крупнее экрана — уменьшаем, чтобы влезла целиком", () => {
    // 200 ширины в 100 экрана → ×0.5, и это выше нижней границы 0.1.
    expect(fitZoom({ w: 200, h: 100 }, { w: 100, h: 100 }, 0.1, 2.6)).toBeCloseTo(0.5);
  });

  it("...но не ниже minZoom: границу камеры вписывание не переступает", () => {
    expect(fitZoom({ w: 200, h: 100 }, { w: 100, h: 100 }, 0.6, 2.6)).toBe(0.6);
  });

  it("берётся МЕНЬШИЙ из двух коэффициентов — иначе вылезет по второй оси", () => {
    // По ширине влезло бы ×2, по высоте только ×1 → берём ×1.
    expect(fitZoom({ w: 100, h: 200 }, { w: 200, h: 200 }, 0.1, 4)).toBeCloseTo(1);
  });

  it("маленькая витрина приближается, но не дальше maxZoom", () => {
    expect(fitZoom({ w: 10, h: 10 }, { w: 1000, h: 1000 }, 0.6, 2.6)).toBe(2.6);
  });

  it("огромная витрина не уходит дальше minZoom — лучше обрезать, чем показать пыль", () => {
    expect(fitZoom({ w: 100000, h: 100000 }, { w: 100, h: 100 }, 0.6, 2.6)).toBe(0.6);
  });

  it("вырожденный экран (0×0 при первом кадре) не даёт NaN", () => {
    const z = fitZoom({ w: 100, h: 100 }, { w: 0, h: 0 }, 0.6, 2.6);
    expect(Number.isFinite(z)).toBe(true);
    expect(z).toBe(0.6);
  });

  it("вырожденная витрина не даёт Infinity", () => {
    const z = fitZoom({ w: 0, h: 0 }, { w: 100, h: 100 }, 0.6, 2.6);
    expect(Number.isFinite(z)).toBe(true);
  });
});
