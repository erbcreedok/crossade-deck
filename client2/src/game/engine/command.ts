// Команда управления доской — ДАННЫЕ (тегированный юнион), а не вызов метода. Единственная форма,
// которой рулят ВСЕ драйверы: палец, девтулс-консоль, сервер, бот/AI, реплей (см. CONTROL-DESIGN.md,
// Ports & Adapters). Движок исполняет их через один `dispatch(cmd)` — это тот choke-point, к которому
// позже цепляются undo / оптимистичная очередь / единый пост-командный синк вида (R2) без ретрофита.
//
// Пока форма минимальная — зеркалит текущие действия BoardAPI. Полный протокол (payload/fx-эмиссия/
// опаковые ключи) — когда появится сервер. `id` — опаковый КЛЮЧ цели (не значение).

export type Command =
  | { t: "flip"; id: string } // перевернуть карту
  | { t: "move"; id: string; x: number; y: number } // переместить пружиной в точку контента
  | { t: "conceal"; id: string; v: boolean } // поставить/снять режим секретности
  | { t: "setValue"; id: string; value: string }; // проставить/придержать значение ("" — придержать)
