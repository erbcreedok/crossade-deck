// КТО ЧТО МОЖЕТ — таблица, а не кнопки.
//
// Решение живёт здесь одним списком правил, а экраны только рисуют то, что им вернули. Если каждое
// место решит само, места разойдутся в первый же день: в списке кик есть, в тултипе нет, а сервер
// пустит обоих.
//
// ТРИ РАЗНЫХ МЕСТА, И ЭТО НЕ ОДНО И ТО ЖЕ:
//
//   "table"   — управление ЧЕЛОВЕКОМ ЗА ЭТИМ СТОЛОМ: стул, права, лок/пин/скрыть, кик.
//               Живёт в ДВУХ местах сразу — в раскрытой строке списка и в тултипе у аватара на
//               сукне, — и потому не может принадлежать ни одному из них.
//   "profile" — то, что про ЧЕЛОВЕКА, а не про стол: дружба. Страница профиля существует в вакууме
//               (из хаба, по ссылке, из чужой игры), и стола вокруг неё может не быть вовсе.
//   "hand"    — ЧУЖАЯ РУКА, раскрытая в тултипе: не кнопки, а ЖЕСТЫ. Правило здесь отвечает не
//               «рисовать ли кнопку», а «слушать ли палец»; поэтому оно ровно такое же по форме,
//               как остальные, и проверяется тем же сервером.
//   "room"    — сама комната: код, видимость, допуск, режим решений, вечность.
//
// НАСЛЕДНИК — АДМИН, И БОЛЬШЕ НИКАКОГО ОЖИДАНИЯ. Оунер ушёл насовсем — комната остаётся на
// админах; ждать его, замораживая стол, незачем. Кому нужна именно корона — делает форк
// (`room:fork`): свою копию с теми же людьми, где оунер он.
//
// ЭТОТ ФАЙЛ — ЧЕРНОВИК СЕРВЕРНОЙ ПРОВЕРКИ. Право, которое проверяет только клиент, — это надпись, а
// не право; поэтому правило написано так, чтобы его можно было выполнить без экрана: (кто я, кто
// он, какая комната) → можно или нет, и почему нет.

(function () {
  /** Роли за столом. Зритель — это «без стула», а не отдельный список наблюдателей. */
  const ROLES = ["оунер", "админ", "игрок", "зритель"];

  /**
   * КТО В КОМНАТЕ РЕШАЕТ — три уровня, по одному слову на каждый.
   *
   *   ВОЛЬНИЦА — каждый админ делает что хочет, не спрашивая никого.
   *   СОВЕТ    — действие админа утверждают админы голосованием; у оунера голос 1.01, и это не
   *              привилегия, а РАЗРЕШИТЕЛЬ НИЧЬИХ: при двух админах «один за, один против» иначе
   *              не разрешается никогда.
   *   ВЕЧЕ     — комнату настраивают все игроки голосованием всех игроков. Зрители не голосуют:
   *              у них нет стула, а значит нет и доли в столе.
   *
   * «Оунер решает один» отдельным режимом не нужен: оунер — тоже админ, и если он не хочет
   * делиться, он просто никого не назначает.
   */
  const MODES = ["вольница", "совет", "вече"];

  /** Одним словом — что этот режим значит. Экраны берут отсюда, чтобы не расходиться в словах. */
  const MODE_MEANS = {
    "вольница": "каждый админ делает что хочет",
    "совет": "действия админов решают админы голосованием",
    "вече": "комнату настраивают все игроки голосованием",
  };

  /** Админ или оунер — те, кому вообще принадлежит управление столом. */
  const isAdmin = (me) => me.role === "оунер" || me.role === "админ";

  function power(me, room) {
    if (me.role === "зритель") return "нет";
    if (room.mode === "вече") return isAdmin(me) || me.role === "игрок" ? "предложение" : "нет";
    if (!isAdmin(me)) return "нет";
    if (room.mode === "совет") return "предложение";
    return me.role === "оунер" ? "полная" : "админ"; // вольница
  }

  /** Распоряжается комнатой — прямо или через голосование. */
  const manages = (p) => p === "полная" || p === "админ" || p === "предложение";

  /**
   * Распоряжается ЛЮДЬМИ — стулом, правами, чужими фигурами. В вече игроки настраивают КОМНАТУ, но
   * не людей: голосованием выгонять соседа — это другая игра, и её никто не заказывал.
   */
  const handles = (me, p) => isAdmin(me) && manages(p);

  /**
   * Можно ли вообще трогать эту руку. Лок проверяется ПЕРВЫМ и бьёт даже оунера: он и ставится
   * затем, чтобы разложенное не разъехалось, пока хозяин отошёл.
   */
  const mayTouch = (me, them, p) => !them.seat ? "он не за столом — руки нет"
    : them.hand["piece:lock"] ? "рука на локе — только смотреть"
    : them.mine || handles(me, p) || "чужой рукой распоряжается админ";

  /**
   * Каждое правило — `may(me, them, room, power)`, вернувшее `true` либо ПРИЧИНУ отказа словами.
   * Причина обязательна: кнопка, пропавшая молча, читается как поломка, и первым делом про неё
   * спрашивают «почему у меня нет кика».
   */
  const RULES = [
    // ---- ЧЕЛОВЕК ЗА ЭТИМ СТОЛОМ ----
    //
    // РУКА ЕСТЬ ТОЛЬКО У ТОГО, КТО СИДИТ. Зрителю нечего локать, пинить и прятать — у него нет
    // фигур; ему остаётся цвет (он есть у всех, потому что цвет — это он сам) и место с правами.
    {
      id: "piece:lock", label: "Лок", where: ["table"], kind: "",
      may: (me, them, room, p) => !them.seat ? "он не за столом — руки нет" : them.mine || handles(me, p) || "чужой рукой распоряжается админ",
    },
    {
      id: "piece:pin", label: "Пин", where: ["table"], kind: "",
      may: (me, them, room, p) => !them.seat ? "он не за столом — руки нет" : them.mine || handles(me, p) || "чужой рукой распоряжается админ",
    },
    {
      id: "piece:hide", label: "Скрытность", where: ["table"], kind: "",
      may: (me, them, room, p) => !them.seat ? "он не за столом — руки нет" : them.mine || handles(me, p) || "чужой рукой распоряжается админ",
    },
    {
      // ЦВЕТ — ЭТО ОН САМ, А НЕ СОСТОЯНИЕ ЕГО РУКИ. У игрока лок и пин живут на нижнем HUD, а цвет
      // — в профиле; значит и здесь они не могут стоять в одной секции. Цвет показывается рядом с
      // лицом, в шапке, где и всё остальное про личность.
      id: "colour", label: "Сменить цвет", where: ["face"], kind: "",
      may: (me, them, room, p) => them.mine || handles(me, p) || "чужой цвет меняет тот, кто распоряжается",
    },
    {
      id: "seat:give", label: "Дать стул", where: ["table"], kind: "gold",
      may: (me, them, room, p) => them.seat ? "он уже за столом" : handles(me, p) || "мест не раздаёшь",
    },
    {
      id: "seat:take", label: "Лишить стула", where: ["table"], kind: "",
      // ОУНЕРА МОЖНО ЛИШИТЬ СТУЛА: он защищён только от кика и от снятия админки.
      may: (me, them, room, p) => !them.seat ? "он и так без стула" : them.mine ? "со своего встают сами" : handles(me, p) || "местами не распоряжаешься",
    },
    {
      id: "admin:grant", label: "Дать админа", where: ["table"], kind: "",
      may: (me, them, room, p) => them.role !== "игрок" && them.role !== "зритель" ? "он уже с правами" : handles(me, p) || "правами не делишься",
    },
    {
      id: "admin:revoke", label: "Забрать админа", where: ["table"], kind: "",
      may: (me, them, room, p) => them.role === "оунер" ? "оунера нельзя разжаловать" : them.role !== "админ" ? "он не админ" : handles(me, p) || "правами не распоряжаешься",
    },
    {
      id: "owner:pass", label: "Передать комнату", where: ["table"], kind: "danger",
      may: (me, them, room, p) => p !== "полная" ? "комнату передаёт только оунер" : them.mine ? "она и так твоя" : them.role === "зритель" ? "сначала посади его" : true,
    },
    {
      id: "kick", label: "Выгнать", where: ["table"], kind: "danger",
      may: (me, them, room, p) => them.role === "оунер" ? "оунера нельзя выгнать" : them.mine ? "себя выгоняют кнопкой «выйти»" : handles(me, p) || "выгонять некому",
    },

    // ---- ЕГО РУКА: ЖЕСТЫ, А НЕ КНОПКИ ----
    //
    // Рука раскрыта ЗАДОМ НАПЕРЁД — так, как её держит он: лицом к нему, а значит РУБАШКАМИ КО
    // МНЕ, и порядок зеркальный — его левая карта у меня справа. Вверх ногами карты не держит
    // никто, и веер стоит ровно, как свой.
    //
    // ЛИЦО ПОКАЗЫВАЕТ ТОЛЬКО ПЕРЕВЁРНУТАЯ КАРТА, и показывает сразу всем: подглядывания в чужую
    // руку в игре нет вовсе. «Скрыть» бьёт даже перевёрнутую — тогда рубашка всегда.
    //
    // ДВА ЗАПРЕТА РАЗНОЙ ПРИРОДЫ, И ИХ НЕЛЬЗЯ СЛИВАТЬ:
    //   ЛОК    — «руками не трогать»: жесты не слушаются, рука видна как была.
    //   СКРЫТЬ — «нечего смотреть»: рубашки ВСЕГДА, и админу тоже.
    // Скрытая рука при этом остаётся управляемой вслепую: карту можно переставить и вынести, не
    // зная, какая она, — ровно как настоящую стопку рубашкой вверх.
    {
      id: "hand:see", label: "Видеть открытое", where: ["hand"],
      may: (me, them) => !them.seat ? "он не за столом — руки нет"
        : them.hand["piece:hide"] ? (them.mine ? true : "рука скрыта — рубашка даже у перевёрнутых") : true,
    },
    {
      id: "hand:sort", label: "Переставить", where: ["hand"], hint: "вдоль",
      may: (me, them, room, p) => mayTouch(me, them, p),
    },
    {
      id: "hand:out", label: "Вынести на стол", where: ["hand"], hint: "вверх",
      may: (me, them, room, p) => mayTouch(me, them, p),
    },
    {
      id: "hand:take", label: "Забрать себе", where: ["hand"], hint: "вниз",
      may: (me, them, room, p) => !me.seat ? "ты без стула — забирать некуда"
        : them.mine ? "она и так твоя" : mayTouch(me, them, p),
    },
    {
      id: "hand:flip", label: "Открыть всем", where: ["hand"], hint: "двойной тап",
      may: (me, them, room, p) => mayTouch(me, them, p),
    },

    // ---- ЧЕЛОВЕК САМ ПО СЕБЕ ----
    {
      id: "friend:add", label: "В друзья", where: ["profile"], kind: "gold",
      may: (me, them) => them.mine ? "это ты" : them.friend === "никто" || "заявка уже есть",
    },
    {
      id: "friend:accept", label: "Принять заявку", where: ["profile"], kind: "gold",
      may: (me, them) => them.friend === "входящий" || "он не звал",
    },
    {
      id: "friend:decline", label: "Отклонить", where: ["profile"], kind: "quiet",
      may: (me, them) => them.friend === "входящий" || "он не звал",
    },
    {
      id: "friend:cancel", label: "Отозвать заявку", where: ["profile"], kind: "quiet",
      may: (me, them) => them.friend === "исходящий" || "заявки нет",
    },
    {
      id: "friend:drop", label: "Убрать из друзей", where: ["profile"], kind: "quiet",
      may: (me, them) => them.friend === "друзья" || "вы не друзья",
    },

    // ---- КОМНАТА ----
    { id: "room:code", label: "Сменить код", where: ["room"], kind: "", may: (me, them, room, p) => manages(p) || "код меняет тот, кто распоряжается" },
    { id: "room:public", label: "Видимость", where: ["room"], kind: "", may: (me, them, room, p) => manages(p) || "видимость меняет тот, кто распоряжается" },
    { id: "room:access", label: "Допуск", where: ["room"], kind: "", may: (me, them, room, p) => manages(p) || "допуск меняет тот, кто распоряжается" },
    {
      // САМ РЕЖИМ ПЕРЕКЛЮЧАЮТ ТОЛЬКО АДМИНЫ, И ДАЖЕ В ВЕЧЕ. Иначе игроки голосованием отменяют
      // вече и любой другой уклад — это уже не настройка комнаты, а смена того, чья она.
      id: "room:mode", label: "Кто решает", where: ["room"], kind: "",
      may: (me, them, room, p) => !isAdmin(me) ? "уклад меняют админы" : manages(p) || "режим меняет тот, кто распоряжается",
    },
    {
      // ВЕЧНОСТЬ ВКЛЮЧАЮТ ВСЕ АДМИНЫ, А СНИМАЮТ ПО-РАЗНОМУ: оунер моментально, админ — с сутками
      // отсрочки. Включение ничего не ломает; снятие — это отложенное удаление, и сутки нужны, чтобы
      // хозяин успел увидеть и вернуть галочку. Само правило «можно» одно на обе стороны, разница
      // живёт в последствии, а не в праве.
      id: "room:forever", label: "Вечная комната", where: ["room"], kind: "",
      may: (me, them, room, p) => manages(p) || "вечность решает тот, кто распоряжается",
    },
    {
      // ФОРК — ОТВЕТ НА «ХОЧУ БЫТЬ ОУНЕРОМ ЭТОЙ КОМНАТЫ». Корону не отбирают: делают свою копию с
      // теми же людьми и правами, где форкнувший — оунер, а остальные приходят админами. Комнат
      // становится две, и это честнее, чем спор об одной.
      id: "room:fork", label: "Своя копия", where: ["room"], kind: "",
      may: (me, them, room, p) => me.role === "оунер" ? "она и так твоя" : p === "нет" ? "копию делает тот, кто распоряжается" : true,
    },
    { id: "room:link", label: "Ссылка", where: ["room"], kind: "gold", may: () => true },
    { id: "room:close", label: "Закрыть комнату", where: ["room"], kind: "danger", may: (me, them, room, p) => p === "полная" || "комнату закрывает оунер" },
  ];

  /**
   * Что можно сделать в месте `where`, и что нельзя — с причинами.
   *
   * В демократии разрешённое остаётся разрешённым, но становится ПРЕДЛОЖЕНИЕМ: та же кнопка, другое
   * слово, другое последствие. Дружба и ссылка голосования не требуют — они не про комнату.
   */
  function actionsOn(where, me, them, room) {
    const p = power(me, room);
    const can = [];
    const cant = [];
    for (const rule of RULES) {
      if (!rule.where.includes(where)) continue;
      const verdict = rule.may(me, them, room, p);
      if (verdict === true) {
        // ЖЕСТ НЕ ГОЛОСУЮТ. Голосование — про решения комнаты, а не про то, как лежат карты: пока
        // собирали голоса, рука уже другая. Кто допущен до руки — тот тянет сразу.
        const personal = rule.id.startsWith("friend") || rule.id.startsWith("hand:") || rule.id === "room:link" || (them.mine && rule.id !== "kick");
        const vote = p === "предложение" && !personal;
        can.push({ id: rule.id, label: vote ? `Предложить: ${rule.label.toLowerCase()}` : rule.label, kind: rule.kind, hint: rule.hint, vote });
      } else {
        cant.push({ id: rule.id, label: rule.label, why: verdict, hint: rule.hint });
      }
    }
    return { power: p, can, cant };
  }

  window.Rights = { ROLES, MODES, MODE_MEANS, power, actionsOn, RULES };
})();
