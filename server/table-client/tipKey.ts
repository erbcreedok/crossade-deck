// ГДЕ ЛЕЖИТ КАРТА — ОДНОЙ СТРОКОЙ. По ней тултип понимает, что карта переехала и его пора закрыть.
//
// ЧИСЛА ОКРУГЛЯЮТСЯ, и это не украшение. Место и угол уплывают в последнем знаке: попросили угол
// `-35.71723456`, на столе оказалось `-35.71723456000001` — обычный дрейф при пересчёте. Ключ,
// склеенный из сырых чисел, от такого «менялся», и тултип кривой карты гас через миг после касания.
// У ровной карты угол ровно `0`, дрейфа нет — оттого баг и цеплялся только к кривым, и выглядело это
// как «по кривым картам нельзя тапнуть».
//
// Ключ отвечает на вопрос «карта ПЕРЕЕХАЛА?», а не «биты те же?». Сотой доли клетки и десятой доли
// градуса с запасом хватает, чтобы заметить настоящий переезд, и с запасом же — чтобы не принять за
// него дрейф.
//
// В РУКЕ — ТОЛЬКО ЧЬЯ РУКА: перестановка карт в руке не переезд, и тултип от неё закрываться не должен.

import type { Snapshot } from "../src/table/contract.js";

/** Сколько знаков оставляем: место — до сотой клетки, угол — до десятой градуса. */
export const TIP_PLACE_DIGITS = 2;
export const TIP_ANGLE_DIGITS = 1;

const близко = (n: number, знаков: number): string => (Math.round(n * 10 ** знаков) / 10 ** знаков).toFixed(знаков);

/** Место карты словами. `null` — карты на столе нет вовсе. */
export function tipKeyOf(s: Snapshot, id: string): string | null {
  const f = s.felt.find((c) => c.id === id);
  if (f) return `felt:${близко(f.x, TIP_PLACE_DIGITS)},${близко(f.y, TIP_PLACE_DIGITS)},${близко(f.angle, TIP_ANGLE_DIGITS)},${f.up}`;
  const pile = s.piles.find((p) => p.cards.at(-1)?.id === id);
  if (pile) return `deck:${pile.id}`;
  const chair = s.chairs.find((c) => c.hand.some((card) => card.id === id));
  return chair ? `hand:${chair.id}` : null;
}
