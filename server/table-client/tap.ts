// ДВОЙНОЙ ТАП — ОДИН ЗАКОН, И ЕГО МОЖНО ПРОВЕРИТЬ.
//
// Пока пара тапов сверялась по имени карты, в тесной руке она почти никогда не складывалась: первый
// тап поднимает карту, веер под пальцем едет, и второй тап садится на соседнюю — а человек всё это
// время держал палец на одном месте. В записи партии это видно как тринадцать пар подряд, где второй
// тап назвал другую карту и переворот не ушёл вовсе.
//
// Поэтому пару собирает ТОЧКА: попал рядом — тот же тап. Целью остаётся карта ПЕРВОГО тапа: в неё
// человек и целился, прежде чем стол под пальцем сдвинулся.

import { DOUBLE_TAP_MS, DOUBLE_TAP_PX } from "./screenConst.js";

/** Тап по карте: какая карта и куда пришёлся палец. */
export interface Tap {
  id: string;
  at: number;
  x: number;
  y: number;
}

/**
 * Какую карту переворачивать, если этот тап — второй в паре.
 *
 * @returns id карты, названной ПЕРВЫМ тапом, или null — пары нет, тап одиночный.
 */
export function doubleTap(last: Tap | null, now: Tap): string | null {
  if (!last) return null;
  if (now.at - last.at >= DOUBLE_TAP_MS) return null;
  const same = last.id === now.id;
  const near = Math.hypot(now.x - last.x, now.y - last.y) < DOUBLE_TAP_PX;
  return same || near ? last.id : null;
}
