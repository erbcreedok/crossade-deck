// РОДЫ СТОЛОВ — каталог. Род стола это ИМЯ КОНФИГА, и ничего кроме.
//
// Здесь единственное место во всём сервере, где имя рода встречается рядом с его правилами. Всё
// остальное — комната, стол, раздача, сеть — работает с `DeskRules`, не зная, как род называется.
// Новый стол появляется строкой в этой таблице; ни одна строчка рантайма при этом не трогается.
//
// Почему не `switch (kind)`: потому что тогда каждый новый род потребовал бы ветки, а следующая
// комбинация правил — ещё одной. Таблица отвечает на все вопросы сразу и не растёт в коде.

import { krestDesk } from "./games/krest.js";
import { SANDBOX, type DeskRules } from "./rules.js";

/**
 * ВСЕ РОДА, КАКИЕ ЕСТЬ. Ключ — то, что приходит снаружи (бот, HTTP); значение — КАК СОБРАТЬ правила.
 *
 * Не готовые правила, а сборщик: у стола может быть своё живое состояние (кто закрыл круг), и два
 * стола одного рода не должны его делить.
 * Песочница стоит первой: это стол, с которого всё началось, и он же ответ на «род не указан».
 */
export type Judge = () => { turn: string | null; closer: string | null } | null;

export const DESKS: Record<string, (judge: Judge) => DeskRules> = {
  sandbox: () => SANDBOX,
  // Крестовому нужен судья: он говорит, чей ход и кто закрыл круг. Судья живёт в КОМНАТЕ, а не в
  // каталоге, — поэтому сюда его передают, а не хранят здесь.
  krest: (judge) => krestDesk(judge),
};

/**
 * ИМЕНА РОДОВ ДЛЯ ЧЕЛОВЕКА — те же, что правила говорят о себе сами (`DeskRules.kind`). Второго
 * списка названий нет нигде: бот берёт их отсюда, и новый род называется ровно там, где написан.
 */
/** Как этот род зовётся для человека. Незнакомый — сам себе имя: комната всё равно открывается. */
export const deskName = (kind: string): string => (isDesk(kind) ? DESKS[kind]!(() => null).kind : kind);

/** Какой набор крупье эта игра предлагает по умолчанию. */
export const deskCrew = (kind: string): string | undefined => (isDesk(kind) ? DESKS[kind]!(() => null).crew : undefined);

export const deskNames = (): Array<{ id: string; name: string }> =>
  Object.entries(DESKS).map(([id, make]) => ({ id, name: make(() => null).kind }));

/** Род, которым открывается стол, если про род ничего не сказали. */
export const DEFAULT_DESK = "sandbox";

/** Есть ли такой род. Разбор пришедшего значения идёт по таблице, а не по перечню имён в коде. */
export const isDesk = (kind: unknown): kind is string => typeof kind === "string" && Object.hasOwn(DESKS, kind);

/**
 * ПРАВИЛА ПО ИМЕНИ РОДА. Имя незнакомое — песочница: стол всё равно открывается.
 *
 * Это не снисходительность, а требование к выкатке: бот и сервер обновляются порознь, и бот,
 * который уже умеет новый род, не должен ронять сервер, который его ещё не умеет. Человек в худшем
 * случае получит стол, где разрешено всё, — а не закрытую дверь.
 */
export const deskOf = (kind: unknown, judge: Judge = () => null): DeskRules => (isDesk(kind) ? DESKS[kind]!(judge) : SANDBOX);
