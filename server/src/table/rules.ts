// СЛОВАРЬ ПРАВ — то, чем ОТЛИЧАЮТСЯ игры, и единственное место, где они отличаются.
//
// ЗАКОН ВЛАДЕЛЬЦА, ДОСЛОВНО ПО СМЫСЛУ: никаких `if (cheatingEnabled)`, никаких `if (game === …)`,
// никаких двух похожих кусков кода в двух ветках. Стол НЕ ЗНАЕТ, какая на нём игра. Игра — это
// объект правил; мухлёж, переводной, подкидной, строгий — не ветви в коде, а ЗНАЧЕНИЯ здесь.
//
// Тот же закон уже живёт в корне репозитория (`desk.the-runtime-knows-no-game`) и охраняется там
// сторожем. `rules.law.test.ts` распространяет его на этот стол и проверяет то, чего НЕ написано.
//
// ЧТО ЗДЕСЬ НЕ ЖИВЁТ: свойства ЗОНЫ — закрыта ли приёмка, приколота ли стопка, видна ли рука. Это
// не правила игры, а состояние предмета на столе, и его меняют руками во время любой игры.

import type { Face, ZonePose } from "./contract.js";
import { yes, type Key, type Verdict } from "./access.js";

/** Где лежит карта, в словах правил: сукно, стопка или чья-то рука. */
export type Spot = { in: "felt" } | { in: "deck"; pile: string } | { in: "hand"; chair: string };

/**
 * ЧТО ПРАВИЛА МОГУТ СПРОСИТЬ У СТОЛА — и ничего сверх этого.
 *
 * Узкое окно нарочно: правила читают стол, но не правят его. Всё, что правила захотят изменить,
 * они возвращают ответом, а меняет — стол.
 */
export interface DeskAsk {
  /** Лицо карты: масть и номинал. Неизвестна — карты нет на столе. */
  face(id: string): Face | undefined;
  /** Карты стопки снизу вверх. */
  pile(id: string): readonly string[];
  /** Карты руки в её порядке. */
  hand(chair: string): readonly string[];
  /** Он ли распорядитель стола. */
  admin(key: string): boolean;
  /** Стул крупье: ему можно то, чего нельзя игрокам. */
  croupier(chair: string): boolean;
}

/**
 * ЗОНА, КОТОРУЮ РОД СТОЛА ПРИНОСИТ С СОБОЙ — данные, и ничего кроме.
 *
 * Стол заводит эти зоны при рождении. Чтобы на сукне появилось новое место, дописывают строку сюда
 * и НЕ ТРОГАЮТ рантайм — это и есть проверка 3б.
 */
export interface DeskZone {
  /** Как место зовётся для человека: «Круг хода». Нет имени — обычная «Стопка». */
  name?: string;
  id: string;
  /** Где стоит, в единицах сукна: середина стола — ноль. */
  x: number;
  y: number;
  /** Как в ней ложатся карты. */
  pose: ZonePose;
  /** Поворот на сукне, в градусах по часовой. */
  angle?: number;
  /** Стоит всегда, даже опустев: у кольца крестового так, у собранной игроками стопки — нет. */
  forever?: boolean;
  /**
   * МЕСТ В КОЛЬЦЕ — не меньше и не больше (поза `ring`). Числа, не правила: партия ставит оба по
   * числу играющих. Не заданы — три и сколько угодно.
   */
  least?: number;
  most?: number;
  /** Замки, с которыми зона рождается (`PILE_GUARDS`). */
  lock?: boolean;
  shut?: boolean;
  seal?: boolean;
  pin?: boolean;
}

/**
 * ЧТО ИМЕННО ПРОИСХОДИТ — всё, что игре нужно знать о ходе, одним значением.
 *
 * Поля необязательны: у вопроса про стол нет карты, у вопроса про карту нет стула. Игра берёт то,
 * что ей нужно, и молчит про остальное.
 */
export interface Move {
  /** Кто делает. */
  by: string;
  /** Карта, о которой речь. */
  card?: string;
  /** Куда кладут или откуда берут. */
  at?: Spot;
  /** Карта, которую накрывают: «бьёт ли» — это про неё. */
  over?: string;
  /** Стопка, если действие про стопку целиком. */
  pile?: string;
  /** Стул, если действие про руку. */
  chair?: string;
  /** Несут стопку целиком, а не одну карту. */
  whole?: true;
}

/**
 * ИГРА — ЭТО ОБЪЕКТ ПРАВИЛ. Больше в ней ничего нет.
 *
 * ОДИН ВОПРОС НА ВСЁ: «что скажешь про этот ключ и этот ход?». Ответ — тот же `Verdict`, что у
 * замков и у набора (`access.ts`), и складывается он с ними одним разбором. Своих методов у игры
 * нет: иначе для каждой новой мысли заводился бы седьмой, восьмой, девятый.
 */
export interface DeskRules {
  /** Зоны, которые род стола приносит с собой. Песочнице хватает колоды — у неё их нет. */
  readonly zones: readonly DeskZone[];
  /**
   * СТОИТ ЛИ КОЛОДА ПУСТОЙ. У песочницы — да: колода это место, с которого всё начинается. В играх,
   * где колоду раздают до конца, пустое место посреди сукна только мешает — раздали, и её нет.
   */
  readonly deckForever?: boolean;
  /** Имя рода стола — для людей и для карточки комнаты, а не для ветвлений. */
  readonly kind: string;
  /**
   * КАКОЙ КРУПЬЕ ПОДХОДИТ ЭТОЙ ИГРЕ — предложение, а не приказ (`crews.ts`). Комната вправе взять
   * другой набор: крупье — деталь конструктора, а не часть правил.
   */
  readonly crew?: string;
  /**
   * КЛЮЧИ, КОТОРЫЕ ЭТА ИГРА ДОБАВЛЯЕТ ВСЕМ (`access.ts`). Пусто у всех, кроме игр, где какое-то дело
   * открыто каждому за столом.
   */
  keys?(): readonly Key[];
  /** Что игра скажет про этот ход. `true` — ей нечего добавить; отказ — с названной причиной. */
  says(ask: DeskAsk, key: Key, move: Move): Verdict;
}

/**
 * ПЕСОЧНИЦА — СТОЛ, ГДЕ РАЗРЕШЕНО ВСЁ. Не «стол без правил»: правила есть, и все они говорят «да».
 *
 * Это и делает мухлёж не флагом, а пресетом: включить мухлёж в любой игре — значит подставить
 * ответы песочницы, а не добавить ветку в код.
 */
export const SANDBOX: DeskRules = {
  kind: "песочница",
  crew: "sandbox",
  zones: [],
  says: () => yes,
};
