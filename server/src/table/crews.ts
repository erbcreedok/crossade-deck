// НАБОРЫ КРУПЬЕ — каталог, отдельный от каталога игр.
//
// Крупье не принадлежит игре. Это отдельная деталь конструктора: крестовый с крупье от дурака —
// законная комбинация, а не поломка. Игра лишь ПРЕДЛАГАЕТ набор по умолчанию (`DeskRules.crew`);
// комната хранит свой выбор и меняет его кнопкой, как род стола.
//
// Набор — это СПИСОК ДЕЛ и ничего больше. Что каждое дело значит, знает стол (`TableRoom`), а не
// каталог: здесь нет ни карт, ни правил, ни ветвлений про игру.

/**
 * РАЗДЕЛЫ ДЕЛ КРУПЬЕ — по тому, ЧТО человек собирается сделать, а не по тому, кто их исполняет.
 *
 * Кнопки лежали двумя кучами в разных местах окна: часть внутри, часть под ним, игровые вперемешку
 * с хозяйственными, и понять, что за что отвечает, было нельзя. Раздел — это ответ на вопрос «я
 * сейчас про партию, про раздачу или про сам стол?».
 */
export type CrewPart = "игра" | "колода" | "рука" | "стол";
export const CREW_PARTS: readonly CrewPart[] = ["игра", "колода", "рука", "стол"];

/** Что умеет крупье этого набора. Имя дела — то, что приходит с кнопки. */
export interface CrewAct {
  /** Имя дела: с ним приходит нажатие. */
  id: string;
  /** Как дело зовётся на кнопке. */
  name: string;
  /** В каком разделе окна стоит кнопка. */
  part: CrewPart;
  /** Только распорядитель стола. Иначе — любой, кого пускает замок стула крупье. */
  adminOnly?: true;
}

export interface Crew {
  /** Имя набора для человека: его видно в комнате и в меню бота. */
  readonly name: string;
  readonly acts: readonly CrewAct[];
}

/**
 * КОЛОДА В РУКАХ КРУПЬЕ — её состав меняет распорядитель: 36 ↔ 52 и джокеры. Недостающие карты
 * прилетают крупье в руки, лишние уходят со стола, откуда бы ни лежали.
 */
const DECK_ACTS: readonly CrewAct[] = [
  { id: "deck", name: "Сменить 36/52", part: "колода", adminOnly: true },
  { id: "jokers", name: "Джокеры вкл/выкл", part: "колода", adminOnly: true },
];

/**
 * ВСЕ НАБОРЫ, КАКИЕ ЕСТЬ. Ключ — то, что приходит снаружи (бот, HTTP); значение — что крупье умеет.
 *
 * Пустой набор — не «крупье выключен», а крупье без дел: он сидит, держит карты, ему можно отдать
 * стопку.
 */
/**
 * ОДИН НАБОР НА ВСЕ РОДА СТОЛА — пока. Крупье песочницы и крестового обязаны уметь одно и то же:
 * расхождение между ними — не свойство игры, а недоделка одного из двух.
 */
const TABLE_ACTS: readonly CrewAct[] = [
  // Собирает ВСЁ: сукно, стопки, круг хода и все руки, включая свою, — чтобы на руках оказалась
  // целая колода. Только админ: это конец партии, а не ход.
  { id: "collect", name: "Собрать колоду", part: "колода", adminOnly: true },
  ...DECK_ACTS,
  // РУКА КРУПЬЕ — его собственные карты: выложить их перед собой или повернуть лицом. Это не про
  // стол, а про то, что он держит, — и раздел у них свой.
  { id: "layout", name: "Выложить карты перед собой", part: "рука" },
  // Рассадка: распорядитель тянет стулья по кромке, где хочет, и подтверждает. Само дело исполняет
  // экран (режим), комнате приходит уже итог — команда `seat/place`.
  { id: "reseat", name: "Передвинуть стулья", part: "стол", adminOnly: true },
];

/**
 * СОБРАТЬ КРУГ — дело крупье, а не игрока: закрытый круг уходит к нему в руки, и стол чист.
 *
 * Это единственное дело, привязанное к РОДУ стола, и привязка законная: круг хода — место,
 * объявленное игрой (`DeskRules.zones`), и в песочнице его попросту нет. Остальные дела одинаковы
 * у всех наборов нарочно — расхождение там было бы недоделкой одного из двух, а не свойством игры.
 *
 * Доступно всем, кого пускает замок стула крупье: просит обычно тот, кто закрыл круг, — и человек
 * кнопкой, и бот репликой.
 */
const RING_ACT: CrewAct = { id: "ring", name: "Собрать круг", part: "игра" };

/**
 * ВЕРНУТЬ КРУГ — отмена для того, кто нажал не туда. Возвращаются ИМЕННО те карты, что собрали
 * прошлый раз, и только в ПУСТОЙ круг.
 *
 * Условие про пустоту — не придирка: успел кто-то положить карту, и круг уже новый; вернуть в него
 * прошлую кучу значило бы подменить чужой ход. Хочешь вернуть — сперва освободи круг.
 */
const RING_BACK: CrewAct = { id: "ring-back", name: "Вернуть круг", part: "игра" };

/**
 * УКАЗАТЬ ХОД — стрелка переезжает туда, куда скажет ведущий.
 *
 * Партия идёт не по книжке: кто-то отвлёкся, кто-то сходил вне очереди, стол переложили руками.
 * Спорить с этим судье нечем — но у стола есть тот, кто решает такие споры вслух, и это крупье.
 */
const POINT_ACT: CrewAct = { id: "point", name: "Указать ход", part: "игра", adminOnly: true };

/**
 * УКАЗАТЕЛЬ ХОДА — стрелка у того, от кого ждут действия. Дело ИГРЫ, а не стола: в песочнице партии
 * нет вовсе, и указывать там нечего — кнопка «включить стрелку» на столе без очереди сбивает с толку.
 */
const MARK_ACT: CrewAct = { id: "turn-mark", name: "Указатель хода", part: "игра", adminOnly: true };

export const CREWS: Record<string, Crew> = {
  sandbox: { name: "песочница", acts: TABLE_ACTS },
  krest: { name: "крестовый", acts: [RING_ACT, RING_BACK, POINT_ACT, MARK_ACT, ...TABLE_ACTS] },
};

/** Набор, которым открывается комната, если про набор ничего не сказали. */
export const DEFAULT_CREW = "sandbox";

/** Есть ли такой набор. Разбор пришедшего значения идёт по таблице, а не по перечню имён в коде. */
export const isCrew = (crew: unknown): crew is string => typeof crew === "string" && Object.hasOwn(CREWS, crew);

/** Набор по имени. Незнакомое имя — песочница: комната всё равно открывается. */
export const crewOf = (crew: unknown): Crew => (isCrew(crew) ? CREWS[crew]! : CREWS[DEFAULT_CREW]!);

/** Имена наборов для человека — по ним бот рисует кнопки выбора. */
export const crewNames = (): Array<{ id: string; name: string }> => Object.entries(CREWS).map(([id, c]) => ({ id, name: c.name }));

/** Дело этого набора по имени. Нет такого дела — `undefined`, и стол откажет. */
export const actOf = (crew: unknown, act: string): CrewAct | undefined => crewOf(crew).acts.find((a) => a.id === act);
