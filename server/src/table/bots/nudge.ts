// КОГДА БОТУ ХОДИТЬ — и почему не сразу.
//
// Бот ходит, когда СТОЛ ЗАМОЛЧАЛ: его очередь, и с последнего чужого движения прошла его пауза.
// Пока люди спорят, админ правит руки, а кто-то держит карту в воздухе — бот ждёт. Ход, влетевший
// человеку под руку, читается не как «бот сходил», а как «стол дёрнулся сам», и это худшее, что
// может сделать бот за столом.
//
// Здесь только решение «пора или нет» — чистое и проверяемое часами теста. Сам ход делает комната.

/** Что видно про стол в этот миг. */
export interface Quiet {
  /** Идёт команда стола (раздача, сбор): руки людей и ботов до её конца стол не трогает. */
  busy: boolean;
  /** Кто-то держит карту — палец на столе. */
  handsOn: boolean;
  /** Когда стол шевелился в последний раз. */
  stirredAt: number;
  now: number;
}

/**
 * ПОРА ЛИ ЭТОМУ БОТУ.
 *
 * @param waitMs своя пауза этого характера — у каждого бота она разная, иначе за столом из четырёх
 *               ботов ходы падают строем и стол читается как машина.
 */
export function ready(q: Quiet, waitMs: number): boolean {
  if (q.busy || q.handsOn) return false;
  return q.now - q.stirredAt >= waitMs;
}

/**
 * ЧЕРЕЗ СКОЛЬКО ЗАГЛЯНУТЬ СНОВА. Ноль — прямо сейчас; иначе столько, сколько осталось до конца
 * паузы. Стол занят или кто-то держит карту — заглядываем через самый короткий срок из живых
 * характеров: причина уйдёт не по часам, а по чужому движению.
 */
export function nextLook(q: Quiet, waits: readonly number[]): number {
  const shortest = waits.length === 0 ? 0 : Math.min(...waits);
  if (q.busy || q.handsOn) return shortest;
  const left = waits.map((wait) => Math.max(0, wait - (q.now - q.stirredAt)));
  return left.length === 0 ? shortest : Math.min(...left);
}
