// КОГДА БОТУ ХОДИТЬ — и почему не сразу.
//
// Бот ходит, когда СТОЛ ЗАМОЛЧАЛ: его очередь, и с последнего чужого движения прошла его пауза.
// Пока люди спорят, админ правит руки, а кто-то держит карту в воздухе — бот ждёт. Ход, влетевший
// человеку под руку, читается не как «бот сходил», а как «стол дёрнулся сам», и это худшее, что
// может сделать бот за столом.
//
// Здесь только решение «пора или нет» — чистое и проверяемое часами теста. Сам ход делает комната.

/**
 * ШЕВЕЛЬНУЛ ЛИ ЭТОТ ЖЕСТ СТОЛ — то есть надо ли боту переждать.
 *
 * Пауза защищает от ОДНОГО: бот не должен положить карту человеку под руку. Значит и считать надо
 * только то, что ДВИГАЕТ ВЕЩИ: карты, стопки, их порядок и стороны.
 *
 * Флаги стула, поза руки, выделение, взгляды, синхронизация и кнопки настроек к игре не относятся:
 * щёлкать замком на чужой руке можно хоть минуту, и стол от этого не шевелится. Пока сюда попадало
 * всё подряд, боты замирали от каждого нажатия — стол казался сломанным, хотя ждал по правилу.
 */
export function stirs(intent: { t: string }): boolean {
  switch (intent.t) {
    // РУКИ НА ВЕЩАХ.
    case "grab":
    case "hold":
    case "drop":
    case "release":
    case "grip":
    case "turn":
    case "flip":
    case "arrange":
    case "gather":
    case "massDrop":
    case "pileDrop":
    case "deckMove":
    case "deckDo":
      return true;
    // ВСЁ ОСТАЛЬНОЕ — не про карты: флаги, позы, места, выделение, взгляды, речь, синхронизация.
    default:
      return false;
  }
}

/**
 * ТАКТ СТОЛА — меньше этого не ходит никто, какой бы быстрый характер ни был.
 *
 * Пауза характера отсчитывается от того мига, когда предыдущий ход ЗАПИСАН, а человек видит его
 * позже: карта ещё летит через стол, ложится, и только тогда ход прочитан. Полторы секунды на это
 * уходит всегда, и самый быстрый характер (1.2 с) успевал положить свою карту раньше, чем чужая
 * долетала, — за столом это читалось как «двое сходили одновременно», особенно после долгой мысли
 * соседа.
 *
 * Разнообразие характеров от этого не страдает: границу задевает только самый нетерпеливый.
 */
export const BOT_BEAT_MS = 1700;

/** Пауза этого характера с учётом такта стола. */
export const beatOf = (waitMs: number): number => Math.max(BOT_BEAT_MS, waitMs);

/** Что видно про стол в этот миг. */
export interface Quiet {
  /** Идёт команда стола (раздача, сбор): руки людей и ботов до её конца стол не трогает. */
  busy: boolean;
  /** Кто-то держит карту — палец на столе. */
  handsOn: boolean;
  /** Когда стол шевелился в последний раз. */
  stirredAt: number;
  now: number;
}

/**
 * ПОРА ЛИ ЭТОМУ БОТУ.
 *
 * @param waitMs своя пауза этого характера — у каждого бота она разная, иначе за столом из четырёх
 *               ботов ходы падают строем и стол читается как машина.
 */
export function ready(q: Quiet, waitMs: number): boolean {
  if (q.busy || q.handsOn) return false;
  return q.now - q.stirredAt >= waitMs;
}

/**
 * ЧЕРЕЗ СКОЛЬКО ЗАГЛЯНУТЬ СНОВА. Ноль — прямо сейчас; иначе столько, сколько осталось до конца
 * паузы. Стол занят или кто-то держит карту — заглядываем через самый короткий срок из живых
 * характеров: причина уйдёт не по часам, а по чужому движению.
 */
export function nextLook(q: Quiet, waits: readonly number[]): number {
  const shortest = waits.length === 0 ? 0 : Math.min(...waits);
  if (q.busy || q.handsOn) return shortest;
  const left = waits.map((wait) => Math.max(0, wait - (q.now - q.stirredAt)));
  return left.length === 0 ? shortest : Math.min(...left);
}
