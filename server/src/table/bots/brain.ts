// МОЗГ БОТА — один интерфейс, несколько исполнений: скрипт, языковая модель, что угодно дальше.
//
// ТРИ ПРАВИЛА, КОТОРЫЕ ЗДЕСЬ ЗАЩИЩЕНЫ ТИПОМ, А НЕ ПРОВЕРКОЙ:
//
//   1. ВЫБОР ИЗ СПИСКА. Мозгу дают готовые легальные ходы и просят номер. Нелегальный ход
//      невозможен по построению — ни языковая модель, ни ошибка в весах не сходят с ума за столом.
//   2. ЧУЖИХ КАРТ МОЗГ НЕ ВИДИТ. В `BotView` нет и не может быть чужой руки: поля такого нет.
//      Иначе это чит, и никакая честность исполнения его не отменит.
//   3. ПАДЕНИЕ — НЕ БЕДА. Мозг может упасть, зависнуть, вернуть чушь; комната берёт запасной и
//      ходит. Бот, из-за которого встал стол, хуже отсутствия бота.

import type { Face, Where } from "../contract.js";
import type { Facts } from "../games/krestMemory.js";

/**
 * ХОД БОТА — ровно то же, что делает человек: взять карту и положить её КУДА-ТО.
 *
 * Место (`to`) называет ИГРА, а не комната: комната во что играют не знает и знать не должна
 * (`room.knows-no-game`). Она берёт `id`, ведёт его в `to` — и на этом её участие кончается.
 */
export type Move = {
  t: "lay" | "take";
  /** Какую карту вести: своя из руки при `lay`, нижняя из круга при `take`. */
  id: string;
  /** Её лицо — мозгу надо знать, чем он ходит и что поднимает. */
  card: Face;
  /** Куда вести. */
  to: Where;
};

/** Стол глазами бота. Чужих карт здесь нет — есть только их количество. */
export interface BotView {
  /** Круг снизу вверх: `ring[0]` — нижняя, её и поднимают. */
  ring: readonly Face[];
  /** Своя рука. */
  hand: readonly { id: string; face: Face }[];
  /** Остальные по рассадке от себя: следующий за мной — первый. */
  others: readonly { chair: string; name: string; cards: number }[];
  /** Положу — круг закроется, и следующий открываю я. */
  closesIfLay: boolean;
  /** Возьму — кто откроет следующий круг. */
  openerIfTake: string | null;
  /** Что помнит стол. */
  facts: Facts;
}

/**
 * ЧЕМ ОДИН БОТ ОТЛИЧАЕТСЯ ОТ ДРУГОГО. Стратегия — параметр, а не код: скриптовый мозг читает веса,
 * языковой получает `says` текстом. Новый характер — это строка в каталоге, а не новый мозг.
 */
export interface Profile {
  key: string;
  name: string;
  /** Как объяснить характер языковой модели — одной фразой от первого лица. */
  says: string;
  /** Беречь козыри и джокеры: 0 — тратит сразу, 1 — держит до конца. */
  hoards: number;
  /** Играть на закрытие круга, чтобы открыть самому. */
  closes: number;
  /** Бить всегда, когда есть чем, вместо того чтобы взять. */
  presses: number;
  /**
   * СКОЛЬКО ЭТОТ БОТ ДУМАЕТ — своё у каждого. За столом из четырёх ботов ходы не должны падать
   * строем: одинаковая пауза читается как машина, разная — как живые люди.
   */
  waitMs: number;
}

export interface Brain {
  key: string;
  /**
   * СКОЛЬКО ЕМУ ДАТЬ НА ХОД. Скриптовому хватит мига, внешней программе нужны секунды: `claude`
   * отвечает за 5–6 с, и общий короткий срок отправлял бы каждый его ход в запасной мозг.
   */
  thinkMs?: number;
  /**
   * Выбрать ход из списка. Дольше `deadlineMs` или ответ не из списка — комната берёт запасной.
   * Бросать исключения можно: их ловят.
   *
   * `stop` взводится, когда думать стало незачем: комнату закрыли, стол разогнали. Мозг обязан
   * бросить работу — за столом, которого нет, ответ никому не нужен, а платный мозг всё это время
   * тратит деньги впустую.
   */
  choose(legal: readonly Move[], view: BotView, profile: Profile, deadlineMs: number, stop?: AbortSignal): Promise<Move>;
}

/** Тот же ход по смыслу: сравнивать мозговой ответ со списком надо по карте, а не по ссылке. */
export const sameMove = (a: Move, b: Move): boolean => a.t === b.t && a.id === b.id;

/** Ответ мозга, приведённый к списку. Не из списка — `null`, и комната возьмёт запасной. */
export const fromList = (legal: readonly Move[], picked: Move | null | undefined): Move | null =>
  picked === null || picked === undefined ? null : (legal.find((one) => sameMove(one, picked)) ?? null);
