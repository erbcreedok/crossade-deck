// СУДЬЯ ПАРТИИ — то, что у игры есть сверх правил стола: очередь, кто закрыл круг, кто вышел.
//
// Комната про игру не знает. Она знает одно: у рода стола МОЖЕТ быть судья (`desks.ts`), и зовёт его
// в четырёх местах — раздали, сходили, спросили «что сейчас в игре», пишем слепок. Нет судьи — стол
// ведёт себя как песочница. Новая игра со своей партией — это новый судья в `games/`, и ни одной
// строки в комнате.
//
// Чистый модуль: судья видит стол только через `Seats` и ничего не меняет в нём сам.

import type { DealDir, Face, Intent, Play, Where } from "./contract.js";
import type { BotView, Move } from "./bots/brain.js";

/**
 * Что судья видит на столе: стулья с руками, стопки и лицо любой карты.
 *
 * Стопки нужны судье не меньше рук: круг хода — обычная стопка, и партия читает его оттуда, а не из
 * своей памяти. Всё, что здесь есть, читается ЗАНОВО перед каждым ответом: между двумя ходами стол
 * могли переложить руками, и судья должен видеть результат, а не то, что помнил.
 */
export interface Seats {
  chairs: readonly {
    id: string;
    owner: string | null;
    hand: readonly string[];
    croupier?: true;
    /** Место за столом — угол от своей стороны (шесть часов), по часовой. Игре нужен, чтобы класть карту перед игроком. */
    angle: number;
  }[];
  faceOf(card: string): Face | undefined;
  /** Карты стопки снизу вверх. Нет такой стопки — пусто. */
  pile(id: string): readonly string[];
}

export interface Referee {
  /**
   * Раздача кончилась — партия начинается с того, что легло в руки. `dealer` — стул раздавшего.
   *
   * `dir` — В КАКУЮ СТОРОНУ РАЗДАВАЛИ. Очередь обязана идти туда же: раздали против часовой, а ход
   * пошёл по часовой — и стол читается наоборот, хотя каждый отдельный ход законный.
   */
  start(seats: Seats, dealer: string | null, dir?: DealDir): void;
  /** Партии больше нет: сменили род стола. */
  stop(): void;
  /**
   * Стол уже пропустил этот ход — догнать его. `true` — партия сдвинулась.
   *
   * `from` — ОТКУДА карта пришла, словами самого стола (`ops`), а не догадкой по намерению:
   * намерение говорит только «куда», и по нему перекладывание в своей руке неотличимо от взятия из
   * круга. Стол это знает точно — он же и пишет след карты.
   */
  follow(seats: Seats, by: string, intent: Intent, from?: Where | null): boolean;
  /** Что правам нужно знать о партии — в ключах людей. Партии нет — `null`. */
  /**
   * `out` — КТО УЖЕ ВЫШЕЛ, в порядке выхода: первый вышедший и есть первый победитель.
   *
   * Выход — самое значимое, что бывает за партией, и до сих пор он проходил молча: человек видел
   * только, что рука соседа опустела, и то если смотрел. Объявляет его комната, а не игра.
   */
  view(seats: Seats): { turn: string | null; closer: string | null; out: string[] } | null;
  /**
   * НАЗНАЧИТЬ ХОД РУКОЙ ВЕДУЩЕГО. Партия идёт не по книжке: кто-то отвлёкся, кто-то сходил вне
   * очереди, стол переложили руками. Чинится это словом ведущего — «ходит он», — а не спором судьи
   * со столом. `true` — партия сдвинулась.
   */
  point?(seats: Seats, chair: string): boolean;
  /** Что сейчас в игре глазами этого человека. Партии нет — `null`. */
  play(seats: Seats, viewer: string): Play | null;
  /** Строка для журнала: как партия стоит сейчас. */
  told(): Record<string, unknown>;
  /** Партия как простое значение — в слепок комнаты и обратно. */
  dump(): unknown;
  load(kept: unknown): void;
  /**
   * ЧТО НУЖНО БОТУ НА ЭТОМ СТУЛЕ: законные ходы и стол его глазами. Не его очередь, партии нет или
   * игра ботов не знает — `null`, и комната просто не ходит.
   *
   * Через этот метод комната остаётся не знающей игры: она получает готовый список ходов и отдаёт
   * его мозгу, ни разу не спросив, во что играют.
   */
  bot?(seats: Seats, chair: string): { legal: readonly Move[]; view: BotView } | null;
}
