// ВЕРНУТЬ КРУГ — отмена, которая не должна подменять чужой ход.
//
// Оба условия здесь равноправны, и каждое однажды объяснят живому человеку за столом: «почему не
// возвращается» — потому что круг уже не пуст, и его карта оказалась бы не первой.

import { describe, expect, it } from "vitest";
import { mayReturnRing, type Swept } from "./crewRing.js";

const унесли: Swept = { zone: "ring", ids: ["a", "b", "c"] };
const вРуке = ["x", "a", "b", "c", "y"];

describe("crew.returning-the-ring-must-not-rewrite-someones-move", () => {
  it("круг пуст и карты у крупье — можно", () => {
    expect(mayReturnRing(унесли, [], вРуке)).toBe(null);
  });

  it("КРУГ НЕ ПУСТ — НЕЛЬЗЯ: кто-то уже походил, и его карта стала бы не первой", () => {
    expect(mayReturnRing(унесли, ["чужая"], вРуке)).toBe("круг-не-пуст");
  });

  it("карты уже раздали — нельзя: половинчатый возврат хуже отказа", () => {
    expect(mayReturnRing(унесли, [], ["x", "a", "y"]), "b и c ушли").toBe("карт-нет-в-руке");
    expect(mayReturnRing(унесли, [], []), "рука пуста").toBe("карт-нет-в-руке");
  });

  it("ничего не уносили — возвращать нечего, и это не ошибка", () => {
    expect(mayReturnRing(null, [], вРуке)).toBe("нечего-возвращать");
    expect(mayReturnRing({ zone: "ring", ids: [] }, [], вРуке)).toBe("нечего-возвращать");
  });

  it("порядок в руке не важен — важно, что карты там есть", () => {
    expect(mayReturnRing(унесли, [], ["c", "b", "a"])).toBe(null);
  });
});
