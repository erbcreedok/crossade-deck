/** Одноразовая перестановка руки: не держится — следующая карта ляжет, куда её положат. */
export type Arrange = "suit" | "rank" | "reverse" | "shuffle";

export interface Chair extends ChairFlags {
  id: string;
  /** Стул крупье: стоит вне кольца, места игрока не занимает, и играть с него нельзя. */
  croupier?: true;
  /**
   * РОВНАЯ РУКА — вся одной стороной. Одну карту в ней не перевернуть: переворачивается вся рука
   * разом. Положенная в неё карта ложится той стороной, какой лежит рука; пустая ровная рука
   * принимает рубашкой вверх.
   *
   * Так держит карты крупье: у него на руках колода, а не расклад, и «одна карта лицом» в колоде —
   * это не ход, а ошибка, которую потом никто не заметит.
   */
  even?: true;
  /** Место за столом — угол в градусах от своей стороны (шесть часов), по часовой. */
  angle: number;
  /** Кто сидит. `null` — стул покинут. */
  owner: string | null;
  pose: HandPose;
  hand: SeenCard[];
}

/**
 * ПРАВИЛА СТОЛА — то, что можно менять на лету, посреди игры. Пока их никто не переключает, но это
 * данные, а не код: новое правило — новое поле здесь и ветка там, где оно действует.
 */
export interface TableRules {
  /** Покинутый стул без карт и не вечный — удаляется. */
  dropEmptyChairs: boolean;
  /** Лица карт — одни на весь стол, выбирает админ. */
  faces: CardFaces;
  /** Рубашка — одна на весь стол, выбирает админ. */
  back: CardBack;
  /**
   * УКАЗАТЕЛЬ ХОДА — стрелка у стула того, от кого сейчас ждут действия.
   *
   * Ничего не запрещает и ничего не двигает: это ответ на вопрос, который за настоящим столом
   * задают вслух — «мой ход?». Вернувшийся к столу через минуту читает круг сам, а вот чья очередь
   * — по кругу не видно никак, и спросить некого, если за столом машины.
   *
   * Выключается распорядителем через крупье: за столом, где считают ходы в уме, подсказка мешает.
   */
  turnMark: boolean;
}

/**
 * КОЛОДА НА ВИД — лица и рубашка из готовых растров `game-presets/cards` (`decks/baked/`). Четыре цвета и
 * кириллица — личные настройки человека, не стола; здесь их нет.
 */
export const CARD_FACES = ["classic", "minimal"] as const;
export type CardFaces = (typeof CARD_FACES)[number];
export const CARD_BACKS = ["plaid", "argyle", "club", "lattice", "crest", "ink"] as const;
export type CardBack = (typeof CARD_BACKS)[number];

export const DEFAULT_RULES: TableRules = { dropEmptyChairs: true, faces: "classic", back: "plaid", turnMark: true };

/** Лица по пресету: белка — классика, остальные — минимал. Рубашку пресет не трогает. */
export const PRESET_FACES: Record<Game, CardFaces> = { belka: "classic", durak: "minimal", krest: "minimal" };

/**
 * СЛЕД КАРТЫ — кто её последним переносил, откуда и когда. Пишется при каждом дропе, сдвиг по сукну тоже
 * перенос. Имена сохраняются в момент хода: ушедший из-за стола остаётся подписанным.
 * `hand` — чья это была рука, если карта пришла из руки. `at` — часы сервера (`Welcome.now`).
 */
export interface Trail {
  by: string;
  byName: string;
  /**
   * КАРТУ ПРИНЕСЛА РАЗДАЧА — не догадка по виду движения, а факт: так сказал тот, кто её вёл.
   *
   * Журналу без этого пришлось бы угадывать раздачу по тому, что карты идут из колоды по рукам
   * подряд. Но крупье может и просто выдать всем по карте — и это НЕ раздача; угадывание тут врёт.
   */
  deal?: true;
  from: "deck" | "hand" | "felt";
  hand?: string;
  /**
   * ИЗ КАКОЙ СТОПКИ — её имя для человека («Круг хода»). У колоды имени нет: она одна и зовётся
   * колодой. Без него карта, вынутая из круга, врала бы, что пришла из колоды.
   */
  pile?: string;
  at: number;
}

/** Всё, что зритель знает о столе. Сервер собирает его для каждого отдельно (`Table.seenBy`). */
export interface Snapshot {
  v: number;
  people: Person[];
  chairs: Chair[];
  /** Стопки — в порядке «кто сверху»: поставленная последней лежит поверх остальных. */
  piles: Pile[];
  felt: FeltCard[];
  /** Следы карт по id — у карт, которые хоть раз переносили. */
  trails: Record<string, Trail>;
  /** Кто что держит: id вещи → key человека. */
  locks: Record<string, string>;
  /**
   * ВЫДЕЛЕНИЕ ЛАССО — id карты → key выделившего. Выделение — лок: чужую выделенную карту не выделить, не взять,
   * не перевернуть и не собрать. Держится, пока выделивший не снимет его или не уйдёт со стола.
   */
  picks: Record<string, string>;
  rules: TableRules;
  /** Кто админ — создатель комнаты, пока он за столом. `null` — его нет. */
  admin: string | null;
  /** Кто раздающий этой сессии. `null` — роль никому не выдана. */
  dealer: string | null;
  /**
   * МОИ ПРАВА (`access.ts`) — списком, а не «я админ». Экран рисует кнопки по нему и не спрашивает,
   * кто перед ним: второго списка прав в клиенте нет и быть не должно.
   */
  rights: string[];
  /** ЧТО СЕЙЧАС В ИГРЕ — состояние, из которого экран выводит подсказки. `null` — партии нет. */
  play: Play | null;
}

/**
 * СОСТОЯНИЕ ПАРТИИ ГЛАЗАМИ ОДНОГО ЧЕЛОВЕКА.
 *
 * Не список правил и не готовые кнопки — СОСТОЯНИЕ: чей ход, что лично мне сейчас можно положить,
 * можно ли взять, кончилась ли партия. Из него экран рисует подсветку сам, тем же разбором, что и
 * сервер; а меняется оно событиями — начался круг, сменилась очередь, вышел игрок.
 */
export interface Play {
  /** Чей ход — ключ человека. `null` — партия кончена. */
  turn: string | null;
  /** Кто закрыл последний круг: у него живой грип кольца. */
  closer: string | null;
  /** Какие карты МОЕЙ руки лягут прямо сейчас — по ним горит подсветка. */
  lay: string[];
  /** Можно ли мне взять со стола. */
  take: boolean;
  /** Проигравший, когда партия кончилась. */
  loser: string | null;
}

