export type TableCommand =
  | { t: "collect" }
  /** Посадить крупье или убрать его. Убранный роняет свои карты на стол закрытой стопкой. */
  | { t: "croupier"; on: boolean }
  /**
   * ПОСАДИТЬ ИГРОКОВ БЕЗ ЧЕЛОВЕКА — `n` штук; `0` уводит всех разом.
   *
   * Стол не спрашивает, откуда пришёл игрок: телеграм, ссылка, переписка — это дело двери. Бот такая
   * же дверь, просто за ней никого нет. Нужны они не только для проверок: пустой стол на четверых
   * нельзя ни разложить, ни раздать, а собирать живых людей ради каждой правки — не работа.
   */
  | {
      t: "bots";
      n: number;
      /** Каким мозгом они думают: `greedy` (по умолчанию), `random`, имя внешнего. */
      brain?: string;
      /** Какой характер: `копитель`, `закрывала`, `агрессор`, `новичок`. Не сказан — по кругу. */
      profile?: string;
    }
  | { t: "shuffle" }
  /** Белка — всегда 36 и без джокеров; `size`/`jokers` у неё игнорируются. */
  | { t: "preset"; game: Game; size?: DeckSize; jokers?: boolean }
  /** Вид колоды: лица, рубашка или оба. */
  | { t: "look"; faces?: CardFaces; back?: CardBack }
  | {
      t: "deal";
      rule: DealRule;
      /** Сколько каждому — для `each` и `durak` (по умолчанию 6). */
      n?: number;
      /** Кто раздаёт — ключ, имя или `@username`. По умолчанию — админ. */
      dealer?: string;
      /**
       * ПЕРВЫЙ ПОЛУЧАТЕЛЬ — стул, с которого пошла раздача, и дальше по часовой. Не сказан — по
       * старому: со следующего после раздающего.
       */
      from?: string;
      /** Кому раздавать — стулья списком. Не сказано — всем игровым, кроме крупье. */
      seats?: string[];
      /** КУДА ИДЁТ КРУГ: по часовой (как за настоящим столом, и так по умолчанию) или против. */
      dir?: DealDir;
      /** Не раздавать покинутым стульям. */
      skipEmpty?: boolean;
      /** Раздавать от лица раздающего: его цвет, его курсор, «двигал он». Иначе — от лица бота. */
      asDealer?: boolean;
      /** Карты не собраны — собрать и перемешать без вопросов. */
      force?: boolean;
    }
  /**
   * ПЕРЕРАЗДАЧА — тем же стульям и по тем же правилам, что прошлая раздача, одним нажатием.
   *
   * Стулья берутся из прошлой раздачи: кто ушёл — тому не раздают, кто пришёл — тоже. Первая карта
   * ложится СЛЕДУЮЩЕМУ от нажавшего; нажал не сидящий за столом — от прошлого начального стула.
   */
  | { t: "redeal" }
  /**
   * СОСТАВ СТОЛА — рассадка из меню в чате.
   *
   *   kick    выгнать сидящего из комнаты. Стул остаётся ему же, как будто он вышел сам; пустой
   *           стул без карт при этом уходит — по общему правилу стола.
   *   add     поставить ещё один пустой стул.
   *   sweep   забрать карты этого стула в руку крупье.
   *   dealer  назначить сидящего раздающим; со старого раздающего роль при этом слетает.
   *   swap    поменять два стула местами — вместе с людьми и картами, которые на них.
   */
  | { t: "seat"; do: "kick" | "add" | "sweep" | "dealer" | "swap"; chair?: string; with?: string }
  /** РАССАДКА РУКОЙ: каждому названному стулу — его новый угол; стул крупье не двигают. */
  | { t: "seat"; do: "place"; chairs: { chair: string; angle: number }[] };

