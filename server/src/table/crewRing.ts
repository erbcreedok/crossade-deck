// СОБРАТЬ КРУГ И ВЕРНУТЬ ЕГО — правило отмены, отдельно от комнаты.
//
// Собрать просто: что лежит в круге, уходит крупье в руки. А вот ВЕРНУТЬ — не просто, и здесь
// живёт всё, что делает возврат честным.
//
// ДВА УСЛОВИЯ, И ОБА ОБЯЗАТЕЛЬНЫ:
//
//   1. КРУГ ПУСТ. Успел кто-то положить карту — круг уже НОВЫЙ, и вернуть в него прошлую кучу
//      значило бы подменить чужой ход: его карта оказалась бы не первой, а сверху чужого хлама.
//      Хочешь вернуть — сперва освободи круг.
//   2. КАРТЫ ВСЁ ЕЩЁ У КРУПЬЕ. Раздали их дальше — возвращать нечего. Половинчатый возврат хуже
//      отказа: он тихо соберёт круг не из тех карт, и разбираться будут уже по журналу.

/** Что унесли с круга прошлый раз. */
export interface Swept {
  /** Из какой зоны унесли. */
  zone: string;
  /** Какие карты, снизу вверх. */
  ids: readonly string[];
}

/** Почему вернуть нельзя. `null` — можно. */
export type NoReturn = "нечего-возвращать" | "круг-не-пуст" | "карт-нет-в-руке";

/**
 * МОЖНО ЛИ ВЕРНУТЬ КРУГ.
 *
 * @param swept что унесли прошлый раз; `null` — не уносили
 * @param ring  что в круге сейчас
 * @param hand  рука крупье сейчас
 */
export function mayReturnRing(swept: Swept | null, ring: readonly string[], hand: readonly string[]): NoReturn | null {
  if (!swept || swept.ids.length === 0) return "нечего-возвращать";
  if (ring.length > 0) return "круг-не-пуст";
  const есть = new Set(hand);
  return swept.ids.every((id) => есть.has(id)) ? null : "карт-нет-в-руке";
}
