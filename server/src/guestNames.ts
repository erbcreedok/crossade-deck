import { randomInt } from "crypto";

/** Двадцать прилагательных — те же, что на стенде первой страницы хаба. */
export const GUEST_ADJ = [
  "Оранжевый", "Золотой", "Синий", "Бешеный", "Потный", "Грязный", "Пьяный", "Наглый",
  "Липкий", "Кривой", "Дохлый", "Тухлый", "Мятый", "Драный", "Вонючий", "Дерзкий",
  "Голый", "Жирный", "Хмурый", "Скользкий",
] as const;

/** И двадцать существительных к ним. Четыреста пар — больше, чем людей за столом. */
export const GUEST_NOUN = [
  "сутенёр", "дождь", "барыга", "алкаш", "шулер", "валет", "гопник", "утюг",
  "веник", "чебурек", "таракан", "огурец", "батон", "жлоб", "хряк", "тапок",
  "шакал", "кабан", "носок", "бомж",
] as const;

/**
 * Кличка по номеру пары — прилагательное быстрым разрядом, существительное медленным, ровно как на
 * стенде. Без номера — случайная.
 */
export function guestName(seed?: number): string {
  const n = seed ?? randomInt(GUEST_ADJ.length * GUEST_NOUN.length);
  const adj = GUEST_ADJ[n % GUEST_ADJ.length]!;
  const noun = GUEST_NOUN[Math.floor(n / GUEST_ADJ.length) % GUEST_NOUN.length]!;
  return `${adj} ${noun}`;
}
