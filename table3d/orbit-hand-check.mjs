// СВОБОДНАЯ КАМЕРА (орбита): рука не привязана к экрану и не висит в воздухе — карты лежат стопкой на столе у моего стула; вернулся в «голову» — рука снова у глаза.
//   node orbit-hand-check.mjs [base]
import { createRequire } from "module";
const require = createRequire(new URL("../server/scripts/x.mjs", import.meta.url));
const { chromium } = require("playwright");
const base = process.argv[2] ?? "http://localhost:9590";
const browser = await chromium.launch();
const errors = [];
const checks = [];
const check = (name, ok, got) => checks.push({ name, ok, got });
const p = await browser.newPage({ viewport: { width: 390, height: 844 } });
p.on("pageerror", (e) => errors.push(e.message));
await p.goto(`${base}/?stand&cam=orbit`);
await p.waitForFunction(() => window.__t3d && document.querySelector("#stage canvas"));
await p.waitForTimeout(1500);
const hand = () => p.evaluate(() => { const s = window.__t3d.state(); const c = s.chairs.find((x) => x.owner === window.__t3d.me()); return c.hand.map((h) => ({ t: window.__t3d.cardTarget(h.id), hud: window.__t3d.cardOnHud(h.id)?.onCamera === true })); });
const o = await hand();
check("в орбите карты руки лежат на столе, а не висят в воздухе", o.length > 3 && o.every((c) => c.t[1] < 0.5), o.map((c) => c.t));
check("и лежат стопкой в одном месте", Math.max(...o.map((c) => c.t[0])) - Math.min(...o.map((c) => c.t[0])) < 0.5 && Math.max(...o.map((c) => c.t[2])) - Math.min(...o.map((c) => c.t[2])) < 0.5, o.map((c) => c.t));
check("и не привязаны к экрану", o.every((c) => !c.hud), o.map((c) => c.hud));
await p.evaluate(() => window.__t3d.setCamMode("head")); await p.waitForTimeout(900);
const h = await hand();
check("вернулся в «голову» — рука снова у глаза", h.some((c) => c.hud), h.map((c) => c.hud));
await p.evaluate(() => window.__t3d.setCamMode("orbit")); await p.waitForTimeout(900);
check("и снова на столе в орбите", (await hand()).every((c) => c.t[1] < 0.5));
// ХВАТА И ПЛАВУЧЕГО СЧЁТЧИКА НЕТ: в орбите грипа на худе нет, счётчик стоит там же, где при сложенной руке; верхнюю карту стопки тянуть можно.
const here = (sel) => p.$(`.screen:not(.off) ${sel}`);
const countTop = () => p.evaluate(() => { const e = document.querySelector(".screen:not(.off) .c-count"); return e ? { top: e.style.top, text: e.textContent.trim() } : null; });
check("в орбите хвата (язычка руки) на худе нет", (await here("[data-grip]")) === null);
const orbitCount = await countTop();
check("в орбите счётчик «на столе · N» на месте", !!orbitCount && /на столе/.test(orbitCount.text), orbitCount);
await p.evaluate(() => window.__t3d.setCamMode("head")); await p.waitForTimeout(500);
await p.evaluate(() => window.__t3d.setHandLevel(0)); await p.waitForTimeout(1500);
const headCount = await countTop();
check("и стоит там же, где при сложенной руке в «голове»", !!headCount && headCount.top === orbitCount.top, { orbit: orbitCount, head: headCount });
await p.evaluate(() => window.__t3d.setCamMode("orbit")); await p.waitForTimeout(900);
const topId = await p.evaluate(() => { const s = window.__t3d.state(); const c = s.chairs.find((x) => x.owner === window.__t3d.me()); return c.hand.at(-1).id; });
const at = await p.evaluate((id) => window.__t3d.screenOf(id), topId);
await p.mouse.move(at.x, at.y); await p.mouse.down(); await p.mouse.move(at.x, at.y - 30, { steps: 5 }); await p.mouse.move(at.x + 40, at.y - 80, { steps: 5 });
await p.waitForTimeout(300);
check("верхнюю карту стопки на столе можно потянуть", (await p.evaluate(() => window.__t3d.draggingId())) === topId, await p.evaluate(() => window.__t3d.draggingId()));
await p.mouse.up();
// МОЯ ЗОНА НА СТОЛЕ ПРИНИМАЕТ, как чужая: в свободной камере, пока несёшь карту, у моего места виден контур цвета хозяина; палец в зоне — горит; отпустил — карта в руке.
const mineZone = () => p.evaluate(() => { const s = window.__t3d.state(); const seat = s.people.find((x) => x.key === window.__t3d.me()).seat; return window.__t3d.zoneInfo().find((c) => c.id === seat); });
const handN = () => p.evaluate(() => { const s = window.__t3d.state(); return s.chairs.find((c) => c.owner === window.__t3d.me()).hand.length; });
const n0 = await handN();
const top2 = await p.evaluate(() => { const s = window.__t3d.state(); return s.chairs.find((c) => c.owner === window.__t3d.me()).hand.at(-1).id; });
const t2 = await p.evaluate((id) => window.__t3d.screenOf(id), top2);
await p.mouse.move(t2.x, t2.y); await p.mouse.down(); await p.mouse.move(t2.x + 4, t2.y - 30, { steps: 4 }); await p.mouse.move(150, 300, { steps: 6 }); await p.mouse.up(); await p.waitForTimeout(1200);
check("карта ушла из руки на сукно", (await handN()) === n0 - 1, await handN());
const feltId = await p.evaluate(() => window.__t3d.state().felt.at(-1).id);
const f2 = await p.evaluate((id) => window.__t3d.screenOf(id), feltId);
await p.mouse.move(f2.x, f2.y); await p.mouse.down(); await p.mouse.move(f2.x + 4, f2.y - 20, { steps: 4 }); await p.mouse.move(f2.x + 30, f2.y - 40, { steps: 4 }); await p.waitForTimeout(300);
const z1 = await mineZone();
check("несу карту — у моего места виден контур зоны", z1.zone === true, z1);
check("цвет зоны — цвет хозяина (мой)", z1.color === "#f2c14e", z1.color);
check("палец не в зоне — не горит", z1.lit < 0.15, z1.lit);
await p.mouse.move(z1.screen.x, z1.screen.y, { steps: 8 }); await p.waitForTimeout(300);
const z2 = await mineZone();
check("палец в моей зоне — горит", z2.lit > 0.25, z2.lit);
await p.mouse.up(); await p.waitForTimeout(1200);
check("отпустил в моей зоне — карта в руке", (await handN()) === n0, { n0, now: await handN() });
await browser.close();
check("без ошибок страницы", errors.length === 0, errors);
for (const c of checks) console.log(c.ok ? "ok  " : "FAIL", c.name, c.ok ? "" : JSON.stringify(c.got));
process.exit(checks.every((c) => c.ok) ? 0 : 1);
